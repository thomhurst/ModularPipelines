using ModularPipelines.FileSystem;

namespace ModularPipelines.GitHub;

/// <summary>
/// Options for a generated distributed GitHub Actions workflow.
/// </summary>
public sealed record DistributedWorkflowOptions
{
    /// <summary>
    /// Gets the distributed coordination backend.
    /// </summary>
    public DistributedBackend Backend { get; init; } = DistributedBackend.Redis;

    /// <summary>
    /// Gets the number of additional workers using <see cref="DefaultRunner"/>.
    /// </summary>
    public int ExtraWorkers { get; init; } = 1;

    /// <summary>
    /// Gets the workflow name.
    /// </summary>
    public string Name { get; init; } = "Distributed Pipeline";

    /// <summary>
    /// Gets the workflow triggers. Pull requests are excluded by default because forked workflows
    /// cannot access the Redis repository secret.
    /// </summary>
    public TriggerCondition TriggerCondition { get; init; } = new()
    {
        Push = new TriggerConditionBranches { Branches = ["main"] },
        WorkflowDispatch = new WorkflowDispatch(),
    };

    /// <summary>
    /// Gets the workflow output path.
    /// </summary>
    public FilePath OutputPath { get; init; } = new(".github/workflows/modular-pipelines.yml");

    /// <summary>
    /// Gets the portable executable project to publish once and run on every runner.
    /// </summary>
    public FilePath PipelineProjectPath { get; init; } = new(".");

    /// <summary>
    /// Gets the .NET SDK version installed by the workflow.
    /// </summary>
    public string DotNetVersion { get; init; } = "11.0.x";

    /// <summary>
    /// Gets the optional target framework used to publish, restore, and run the shared host.
    /// </summary>
    public string? DotNetRunFramework { get; init; }

    /// <summary>
    /// Gets the runner used for the master and additional workers.
    /// </summary>
    public string DefaultRunner { get; init; } = "ubuntu-latest";

    /// <summary>
    /// Gets the GitHub Actions secret containing the Redis connection string.
    /// </summary>
    public string RedisSecretName { get; init; } = "REDIS_URL";

    /// <summary>
    /// Gets a value indicating whether the workflow caches NuGet packages.
    /// </summary>
    public bool CacheNuGet { get; init; } = true;

    /// <summary>
    /// Gets environment variables for host publishing in the non-matrix initializer.
    /// Values must use contexts available in that job; matrix expressions are not supported.
    /// </summary>
    public IReadOnlyDictionary<string, string>? PublishEnvironmentVariables { get; init; }

    /// <summary>
    /// Gets additional environment variables for runner restore and pipeline execution.
    /// Values can use matrix expressions. Use <see cref="PublishEnvironmentVariables"/> for host build inputs.
    /// Reserved distributed variables are always generated by the writer.
    /// </summary>
    public IReadOnlyDictionary<string, string>? EnvironmentVariables { get; init; }
}
