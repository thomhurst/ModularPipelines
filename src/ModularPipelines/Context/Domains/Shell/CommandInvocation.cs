using ModularPipelines.Models;
using ModularPipelines.Options;

namespace ModularPipelines.Context.Domains.Shell;

/// <summary>
/// Describes a command after its tool and arguments have been parsed, but before execution.
/// </summary>
/// <remarks>
/// <see cref="ICommandInterceptor"/> implementations can pass a modified copy to the next stage.
/// <see cref="CommandLine"/>, <see cref="ToolOptions"/>, <see cref="ExecutionOptions"/>, and
/// <see cref="WorkingDirectory"/> are applied; <see cref="CommandInput"/> and
/// <see cref="EnvironmentVariables"/> are read-only, secret-masked views regenerated by the framework.
/// </remarks>
/// <param name="CommandLine">The parsed command line. Changes are applied to the executed process.</param>
/// <param name="ToolOptions">The original strongly typed tool options, when available.</param>
/// <param name="ExecutionOptions">The command execution options. Changes are applied to the executed process, except the execution timeout.</param>
/// <param name="CommandInput">The secret-masked command input. Edits are ignored.</param>
/// <param name="WorkingDirectory">The effective working directory. Changes are applied to the executed process.</param>
/// <param name="EnvironmentVariables">The secret-masked environment variables. Edits are ignored; change <see cref="CommandExecutionOptions.EnvironmentVariables"/> instead.</param>
public sealed record CommandInvocation(
    CommandLine CommandLine,
    CommandLineToolOptions? ToolOptions,
    CommandExecutionOptions ExecutionOptions,
    string CommandInput,
    string WorkingDirectory,
    IReadOnlyDictionary<string, string?> EnvironmentVariables);
