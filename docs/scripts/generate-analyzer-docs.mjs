import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..', '..');
const outputDirectory = join(repositoryRoot, 'docs', 'docs', 'analyzers');
const checkOnly = process.argv.includes('--check');

const releaseFiles = [
  {
    path: 'src/ModularPipelines.Analyzers/ModularPipelines.Analyzers/AnalyzerReleases.Shipped.md',
    availability: 'Public analyzer package',
  },
  {
    path: 'src/ModularPipelines.Analyzers/ModularPipelines.Analyzers/AnalyzerReleases.Unshipped.md',
    availability: 'Public analyzer package',
  },
  {
    path: 'src/ModularPipelines.Development.Analyzers/AnalyzerReleases.Shipped.md',
    availability: 'Repository development only',
  },
  {
    path: 'src/ModularPipelines.Development.Analyzers/AnalyzerReleases.Unshipped.md',
    availability: 'Repository development only',
  },
];

const rules = new Map();

for (const releaseFile of releaseFiles) {
  applyReleaseMetadata(
    join(repositoryRoot, releaseFile.path),
    releaseFile.availability,
    rules);
}

const activeRules = [...rules.values()]
  .filter(rule => /^MP(?:\d{4}|[A-Z]+\d{3,4})$/.test(rule.id))
  .sort((left, right) => left.id.localeCompare(right.id));

if (activeRules.length === 0) {
  throw new Error('No active ModularPipelines analyzer rules were found.');
}

const expectedFiles = new Map([
  ['index.md', renderIndex(activeRules)],
  ...activeRules.map((rule, index) => [`${rule.id}.md`, renderRule(rule, index)]),
]);

if (checkOnly) {
  checkGeneratedFiles(expectedFiles);
} else {
  writeGeneratedFiles(expectedFiles);
}

function applyReleaseMetadata(filePath, availability, activeRulesById) {
  let section = '';

  for (const rawLine of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    const heading = /^###\s+(New|Removed|Changed) Rules$/i.exec(line);

    if (heading) {
      section = heading[1].toLowerCase();
      continue;
    }

    if (!section || !line.includes('|') || /^(Rule ID|-+\|)/i.test(line)) {
      continue;
    }

    const columns = line
      .split('|')
      .map(column => column.trim())
      .filter((column, index, values) =>
        column.length > 0 || (index > 0 && index < values.length - 1));

    if (columns.length < 4) {
      continue;
    }

    const [id, category, severity] = columns;
    const notes = section === 'changed'
      ? columns.slice(5)
      : columns.slice(3);

    if (section === 'removed') {
      activeRulesById.delete(id);
      continue;
    }

    const rule = { id, category, severity, description: notes.join(' | '), availability };

    if (section === 'new' && activeRulesById.has(id)) {
      throw new Error(`Duplicate active analyzer rule ID '${id}' in ${filePath}.`);
    }

    if (section === 'new' || activeRulesById.has(id)) {
      activeRulesById.set(id, rule);
    }
  }
}

function renderIndex(allRules) {
  const rows = allRules
    .map(rule =>
      `| [\`${rule.id}\`](./${rule.id}.md) | ${rule.category} | ${rule.severity} | ${rule.availability} | ${sentence(rule.description)} |`)
    .join('\n');

  return `---
title: Analyzer rules
slug: /analyzers
sidebar_position: 1
---

<!-- Generated by scripts/generate-analyzer-docs.mjs from AnalyzerReleases.*.md. -->

# Analyzer rules

| Rule | Category | Default severity | Availability | Description |
|------|----------|------------------|--------------|-------------|
${rows}
`;
}

function renderRule(rule, index) {
  return `---
title: '${rule.id}'
slug: /analyzers/${rule.id}
sidebar_position: ${getSidebarPosition(rule.id, index)}
---

<!-- Generated by scripts/generate-analyzer-docs.mjs from AnalyzerReleases.*.md. -->

# ${rule.id}

${sentence(rule.description)}

| Property | Value |
|----------|-------|
| Category | ${rule.category} |
| Default severity | ${rule.severity} |
| Availability | ${rule.availability} |

## Configure severity

\`\`\`ini title=".editorconfig"
dotnet_diagnostic.${rule.id}.severity = ${getEditorConfigSeverity(rule.severity)}
\`\`\`

Use \`none\` to disable the rule, or \`silent\`, \`suggestion\`, \`warning\`, or \`error\` to change its severity.

## Suppress a specific occurrence

\`\`\`csharp
#pragma warning disable ${rule.id}
// Code that intentionally violates ${rule.id}.
#pragma warning restore ${rule.id}
\`\`\`
`;
}

function getSidebarPosition(id, index) {
  const numericId = /^MP(\d{4})$/.exec(id);
  return numericId ? Number.parseInt(numericId[1], 10) + 1 : 1000 + index;
}

function sentence(value) {
  return /[.!?`]$/.test(value) ? value : `${value}.`;
}

function getEditorConfigSeverity(severity) {
  const normalizedSeverity = severity.toLowerCase();
  switch (normalizedSeverity) {
    case 'error':
    case 'warning':
      return normalizedSeverity;
    case 'info':
      return 'suggestion';
    case 'hidden':
      return 'silent';
    default:
      throw new Error(`Unsupported analyzer severity: ${severity}`);
  }
}

function checkGeneratedFiles(expected) {
  const actualNames = existsSync(outputDirectory)
    ? readdirSync(outputDirectory).filter(name => name.endsWith('.md')).sort()
    : [];
  const expectedNames = [...expected.keys()].sort();
  const failures = [];

  if (actualNames.join('\n') !== expectedNames.join('\n')) {
    failures.push('Generated analyzer documentation file list is stale.');
  }

  for (const [name, content] of expected) {
    const filePath = join(outputDirectory, name);
    const actual = existsSync(filePath)
      ? normalize(readFileSync(filePath, 'utf8'))
      : '';

    if (actual !== normalize(content)) {
      failures.push(`${name} is stale.`);
    }
  }

  if (failures.length > 0) {
    throw new Error(`${failures.join('\n')}\nRun yarn generate-analyzer-docs.`);
  }

  console.log(`Verified ${activeRules.length} generated analyzer rule pages.`);
}

function writeGeneratedFiles(expected) {
  mkdirSync(outputDirectory, { recursive: true });

  for (const existingName of readdirSync(outputDirectory).filter(name => name.endsWith('.md'))) {
    if (!expected.has(existingName)) {
      unlinkSync(join(outputDirectory, existingName));
    }
  }

  for (const [name, content] of expected) {
    writeFileSync(join(outputDirectory, name), normalize(content), 'utf8');
  }

  console.log(`Generated ${activeRules.length} analyzer rule pages.`);
}

function normalize(value) {
  return value.replace(/\r\n/g, '\n');
}
