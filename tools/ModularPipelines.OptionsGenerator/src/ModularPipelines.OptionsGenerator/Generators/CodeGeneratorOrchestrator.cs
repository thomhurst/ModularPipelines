using Microsoft.Extensions.Logging;
using ModularPipelines.OptionsGenerator.External;
using ModularPipelines.OptionsGenerator.Models;
using ModularPipelines.OptionsGenerator.Scrapers.Base;
using ModularPipelines.OptionsGenerator.Scrapers.Cli;
using ModularPipelines.OptionsGenerator.TypeDetection;

namespace ModularPipelines.OptionsGenerator.Generators;

/// <summary>
/// Orchestrates the scraping and code generation process.
/// Supports both CLI-first scrapers (preferred) and HTML scrapers (fallback).
/// </summary>
public class CodeGeneratorOrchestrator
{
    private const string ExternalOwnershipDirectory = ".modular-pipelines-options";
    private const string ExternalOwnershipMarker =
        "# Generated by ModularPipelines.OptionsGenerator. Do not edit.";
    private const string ExternalOwnershipIdentityPrefix = "# Ownership identity: ";

    private static readonly string[] GeneratedCleanupDirectories =
        ["Options", "Services", "Extensions", "Enums"];

    private readonly IEnumerable<ICliScraper> _cliScrapers;
    private readonly IEnumerable<ICliDocumentationScraper> _htmlScrapers;
    private readonly IEnumerable<ICodeGenerator> _generators;
    private readonly ILogger<CodeGeneratorOrchestrator> _logger;
    private readonly OptionTypeEnhancer? _typeEnhancer;

    public CodeGeneratorOrchestrator(
        IEnumerable<ICliScraper> cliScrapers,
        IEnumerable<ICliDocumentationScraper> htmlScrapers,
        IEnumerable<ICodeGenerator> generators,
        ILogger<CodeGeneratorOrchestrator> logger,
        OptionTypeEnhancer? typeEnhancer = null)
    {
        ArgumentNullException.ThrowIfNull(cliScrapers);
        ArgumentNullException.ThrowIfNull(htmlScrapers);
        ArgumentNullException.ThrowIfNull(generators);
        ArgumentNullException.ThrowIfNull(logger);

        _cliScrapers = cliScrapers;
        _htmlScrapers = htmlScrapers;
        _generators = generators;
        _logger = logger;
        _typeEnhancer = typeEnhancer;
    }

    /// <summary>
    /// Generates code for the specified tools.
    /// </summary>
    /// <param name="toolsToGenerate">Comma-separated list of tools or "all".</param>
    /// <param name="outputDirectory">Output directory path.</param>
    /// <param name="useCliFirst">When true, prefer CLI scrapers over HTML scrapers.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    public async Task<GenerationResult> GenerateAsync(
        string toolsToGenerate,
        string outputDirectory,
        bool useCliFirst = true,
        bool approveCommandCoverageShrinkage = false,
        CancellationToken cancellationToken = default)
    {
        var result = new GenerationResult();
        var toolList = ParseToolList(toolsToGenerate);
        var processedTools = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        // Run-wide record of emitted paths, so tools sharing an output directory
        // (e.g. kubectl and kustomize in ModularPipelines.Kubernetes) can't silently
        // overwrite each other's generated files.
        var emittedPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var fileSystemPathComparer = GetFileSystemPathComparer(outputDirectory);

        // Build a lookup of CLI scrapers by tool name
        var cliScrapersByTool = _cliScrapers.ToDictionary(s => s.ToolName, s => s, StringComparer.OrdinalIgnoreCase);

        await ProcessHtmlScrapersAsync(
            toolList,
            cliScrapersByTool,
            processedTools,
            outputDirectory,
            result,
            emittedPaths,
            fileSystemPathComparer,
            useCliFirst,
            approveCommandCoverageShrinkage,
            cancellationToken);

        await ProcessCliOnlyScrapersAsync(
            toolList,
            processedTools,
            outputDirectory,
            result,
            emittedPaths,
            fileSystemPathComparer,
            useCliFirst,
            approveCommandCoverageShrinkage,
            cancellationToken);

        if (!result.HasErrors)
        {
            var registeredToolNames = _htmlScrapers.Select(scraper => scraper.ToolName)
                .Concat(_cliScrapers.Select(scraper => scraper.ToolName))
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToArray();

            CleanupReconciledGeneratedFiles(outputDirectory, registeredToolNames, result.FilesDeleted);
        }

        return result;
    }

    /// <summary>
    /// Generates an integration from a caller-supplied tool definition.
    /// </summary>
    public async Task<GenerationResult> GenerateFromDefinitionAsync(
        CliToolDefinition tool,
        string outputDirectory,
        bool approveCommandCoverageShrinkage = false,
        CancellationToken cancellationToken = default)
    {
        ExternalToolDefinitionLoader.Validate(tool, outputDirectory);
        var ownershipRelativePath = Path.Combine(
            ExternalOwnershipDirectory,
            $"{tool.NamespacePrefix}.files");
        var previousOwnership = FindExternalOwnershipManifest(
            outputDirectory,
            ownershipRelativePath,
            tool.OwnershipId!);
        var previousCoverageManifest = previousOwnership.OwnedPaths
            .FirstOrDefault(path => path.EndsWith(
                ".CommandCoverage.json",
                StringComparison.OrdinalIgnoreCase));
        var previousCoverageManifestPath = previousCoverageManifest is null
            ? null
            : ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
                previousCoverageManifest,
                outputDirectory,
                "previous command coverage manifest");
        var externallyClaimedPaths = GetExternallyClaimedPaths(
            outputDirectory,
            tool.OwnershipId!);
        var fileSystemPathComparer = GetFileSystemPathComparer(outputDirectory);
        var previouslyOwnedFullPaths = previousOwnership.OwnedPaths
            .Select(path => ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
                path,
                outputDirectory,
                "external ownership manifest path"))
            .Select(Path.GetFullPath)
            .ToArray();
        var replaceableExistingPaths = previouslyOwnedFullPaths
            .ToHashSet(fileSystemPathComparer);
        var enumBaselinePaths = GetOwnedEnumPaths(previouslyOwnedFullPaths);

        var result = new GenerationResult
        {
            ToolsProcessed = { tool.ToolName },
        };
        await GenerateForToolAsync(
            tool,
            outputDirectory,
            result,
            externallyClaimedPaths,
            fileSystemPathComparer,
            approveCommandCoverageShrinkage,
            cancellationToken,
            enforceOutputContainment: true,
            cleanupGeneratedFilesByNamespacePrefix: false,
            writeAssemblyInfo: false,
            commandCoverageBaselinePath: previousCoverageManifestPath,
            commandCoveragePathComparer: fileSystemPathComparer,
            allowMissingCommandCoverageManifest: true,
            replaceableExistingPaths: replaceableExistingPaths,
            enumBaselinePaths: enumBaselinePaths,
            beforeWrite: async (candidateOwnedPaths, token) =>
            {
                var journalOwnedPaths = previousOwnership.OwnedPaths
                    .Concat(candidateOwnedPaths)
                    .Select(path => path.Replace('\\', '/'))
                    .Distinct(fileSystemPathComparer)
                    .Order(fileSystemPathComparer)
                    .ToArray();
                await WriteExternalOwnershipManifestAsync(
                    outputDirectory,
                    ownershipRelativePath,
                    tool.OwnershipId!,
                    journalOwnedPaths,
                    token);
            });

        var currentlyOwnedPaths = result.FilesGenerated
            .Select(path => path.Replace('\\', '/'))
            .Distinct(fileSystemPathComparer)
            .Order(fileSystemPathComparer)
            .ToArray();
        var retainedOwnedPaths = ReconcileExternalOwnedFiles(
            outputDirectory,
            previousOwnership.OwnedPaths,
            currentlyOwnedPaths,
            fileSystemPathComparer,
            result.FilesDeleted);
        var manifestOwnedPaths = currentlyOwnedPaths
            .Concat(retainedOwnedPaths)
            .Distinct(fileSystemPathComparer)
            .Order(fileSystemPathComparer)
            .ToArray();
        await WriteExternalOwnershipManifestAsync(
            outputDirectory,
            ownershipRelativePath,
            tool.OwnershipId!,
            manifestOwnedPaths,
            cancellationToken);
        result.FilesGenerated.Add(ownershipRelativePath);
        if (!fileSystemPathComparer.Equals(
                previousOwnership.RelativePath,
                ownershipRelativePath))
        {
            var previousManifestPath = ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
                previousOwnership.RelativePath,
                outputDirectory,
                "previous external ownership manifest");
            if (File.Exists(previousManifestPath)
                && FileContainsMarker(
                    previousManifestPath,
                    ExternalOwnershipMarker,
                    outputDirectory))
            {
                DeleteFileAndRecord(
                    outputDirectory,
                    previousManifestPath,
                    result.FilesDeleted,
                    validateContainment: true);
            }
        }

        return result;
    }

    private static ExternalOwnershipManifest FindExternalOwnershipManifest(
        string outputDirectory,
        string expectedRelativePath,
        string ownershipId)
    {
        var expected = ReadExternalOwnershipManifest(outputDirectory, expectedRelativePath);
        if (expected.Exists)
        {
            if (!string.Equals(expected.OwnershipId, ownershipId, StringComparison.Ordinal))
            {
                throw new InvalidDataException(
                    $"External ownership manifest '{expectedRelativePath}' does not belong to ownership identity '{ownershipId}'.");
            }

            return expected;
        }

        var ownershipDirectory = ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
            ExternalOwnershipDirectory,
            outputDirectory,
            "external ownership directory");
        if (!Directory.Exists(ownershipDirectory))
        {
            return expected;
        }

        foreach (var path in Directory.GetFiles(
                     ownershipDirectory,
                     "*.files",
                     SearchOption.TopDirectoryOnly))
        {
            var relativePath = Path.GetRelativePath(outputDirectory, path);
            var candidate = ReadExternalOwnershipManifest(outputDirectory, relativePath);
            if (string.Equals(candidate.OwnershipId, ownershipId, StringComparison.Ordinal))
            {
                return candidate;
            }
        }

        return expected;
    }

    private static HashSet<string> GetExternallyClaimedPaths(
        string outputDirectory,
        string ownershipId)
    {
        var claimedPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var ownershipDirectory = ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
            ExternalOwnershipDirectory,
            outputDirectory,
            "external ownership directory");
        if (!Directory.Exists(ownershipDirectory))
        {
            return claimedPaths;
        }

        foreach (var path in Directory.GetFiles(
                     ownershipDirectory,
                     "*.files",
                     SearchOption.TopDirectoryOnly))
        {
            var relativePath = Path.GetRelativePath(outputDirectory, path);
            var manifest = ReadExternalOwnershipManifest(outputDirectory, relativePath);
            if (string.Equals(manifest.OwnershipId, ownershipId, StringComparison.Ordinal))
            {
                continue;
            }

            foreach (var ownedPath in manifest.OwnedPaths)
            {
                var fullPath = ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
                    ownedPath,
                    outputDirectory,
                    "external ownership manifest path");
                claimedPaths.Add(
                    Path.GetRelativePath(outputDirectory, fullPath).Replace('\\', '/'));
            }
        }

        return claimedPaths;
    }

    private static ExternalOwnershipManifest ReadExternalOwnershipManifest(
        string outputDirectory,
        string relativePath)
    {
        var manifestPath = ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
            relativePath,
            outputDirectory,
            "external ownership manifest");
        if (!File.Exists(manifestPath))
        {
            return new ExternalOwnershipManifest(relativePath, null, [], Exists: false);
        }

        var lines = File.ReadAllLines(manifestPath);
        if (!lines.Contains(ExternalOwnershipMarker, StringComparer.Ordinal))
        {
            return new ExternalOwnershipManifest(relativePath, null, [], Exists: true);
        }

        var identity = lines
            .FirstOrDefault(line => line.StartsWith(
                ExternalOwnershipIdentityPrefix,
                StringComparison.Ordinal));
        var ownershipId = identity is null
            ? null
            : DecodeExternalOwnershipIdentity(identity[ExternalOwnershipIdentityPrefix.Length..]);
        var ownedPaths = lines
            .Where(line => !string.IsNullOrWhiteSpace(line)
                           && !line.StartsWith('#'))
            .ToArray();
        return new ExternalOwnershipManifest(relativePath, ownershipId, ownedPaths, Exists: true);
    }

    private static string? DecodeExternalOwnershipIdentity(string encodedIdentity)
    {
        try
        {
            return System.Text.Encoding.UTF8.GetString(
                Convert.FromBase64String(encodedIdentity));
        }
        catch (FormatException)
        {
            return null;
        }
    }

    private IReadOnlyList<string> ReconcileExternalOwnedFiles(
        string outputDirectory,
        IReadOnlyCollection<string> previouslyOwnedPaths,
        IReadOnlyCollection<string> currentlyOwnedPaths,
        StringComparer fileSystemPathComparer,
        ICollection<string> deletedPaths)
    {
        var current = currentlyOwnedPaths.ToHashSet(fileSystemPathComparer);
        var retainedPaths = new List<string>();
        foreach (var relativePath in previouslyOwnedPaths.Where(path => !current.Contains(path)))
        {
            var fullPath = ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
                relativePath,
                outputDirectory,
                "external ownership manifest path");
            if (!File.Exists(fullPath))
            {
                continue;
            }

            if (!IsExternallyOwnedGeneratedFile(outputDirectory, fullPath))
            {
                continue;
            }

            if (!DeleteFileAndRecord(
                    outputDirectory,
                    fullPath,
                    deletedPaths,
                    validateContainment: true))
            {
                retainedPaths.Add(relativePath);
            }
        }

        return retainedPaths;
    }

    private static IReadOnlyDictionary<string, string> GetOwnedEnumPaths(
        IEnumerable<string> ownedFullPaths)
    {
        const string generatedSuffix = ".Generated.cs";
        return ownedFullPaths
            .Where(path => string.Equals(
                Path.GetFileName(Path.GetDirectoryName(path)),
                "Enums",
                StringComparison.Ordinal))
            .Where(path => Path.GetFileName(path).EndsWith(
                generatedSuffix,
                StringComparison.Ordinal))
            .GroupBy(
                path => Path.GetFileName(path)[..^generatedSuffix.Length],
                StringComparer.Ordinal)
            .ToDictionary(
                group => group.Key,
                group => group.FirstOrDefault(File.Exists) ?? group.First(),
                StringComparer.Ordinal);
    }

    private static StringComparer GetFileSystemPathComparer(string outputDirectory)
    {
        var probeName = $".modular-pipelines-case-probe-a{Guid.NewGuid():N}";
        var probePath = Path.Combine(outputDirectory, probeName);
        var alternateCasePath = Path.Combine(outputDirectory, probeName.ToUpperInvariant());

        try
        {
            using var probe = new FileStream(
                probePath,
                new FileStreamOptions
                {
                    Mode = FileMode.CreateNew,
                    Access = FileAccess.ReadWrite,
                    Share = FileShare.ReadWrite | FileShare.Delete,
                    Options = FileOptions.DeleteOnClose,
                });
            return File.Exists(alternateCasePath)
                ? StringComparer.OrdinalIgnoreCase
                : StringComparer.Ordinal;
        }
        catch (Exception exception)
            when (exception is IOException or UnauthorizedAccessException)
        {
            return OperatingSystem.IsWindows()
                ? StringComparer.OrdinalIgnoreCase
                : StringComparer.Ordinal;
        }
    }

    private static bool IsExternallyOwnedGeneratedFile(
        string outputDirectory,
        string path) =>
        IsAutoGeneratedFile(path, outputDirectory)
        || FileContainsMarker(
            path,
            "<!-- This file is generated by ModularPipelines.OptionsGenerator. -->",
            outputDirectory)
        || CommandCoverageGuard.IsGeneratedManifest(path, outputDirectory);

    private static async Task WriteExternalOwnershipManifestAsync(
        string outputDirectory,
        string relativePath,
        string ownershipId,
        IReadOnlyCollection<string> ownedPaths,
        CancellationToken cancellationToken)
    {
        var manifestPath = ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
            relativePath,
            outputDirectory,
            "external ownership manifest");
        var content = string.Join(
            Environment.NewLine,
            new[]
                {
                    ExternalOwnershipMarker,
                    ExternalOwnershipIdentityPrefix + Convert.ToBase64String(
                        System.Text.Encoding.UTF8.GetBytes(ownershipId)),
                }
                .Concat(ownedPaths)
                .Append(string.Empty));
        var temporaryPath = $"{manifestPath}.{Guid.NewGuid():N}.tmp";
        try
        {
            await WriteFileAsync(
                temporaryPath,
                content,
                cancellationToken,
                outputDirectory,
                "temporary external ownership manifest");
            ValidateContainedPath(
                outputDirectory,
                manifestPath,
                "external ownership manifest");
            File.Move(temporaryPath, manifestPath, overwrite: true);
        }
        finally
        {
            try
            {
                File.Delete(temporaryPath);
            }
            catch (Exception)
            {
                // The ownership update already failed; do not mask its exception.
            }
        }
    }

    private async Task ProcessHtmlScrapersAsync(
        List<string> toolList,
        IReadOnlyDictionary<string, ICliScraper> cliScrapersByTool,
        ISet<string> processedTools,
        string outputDirectory,
        GenerationResult result,
        HashSet<string> emittedPaths,
        StringComparer fileSystemPathComparer,
        bool useCliFirst,
        bool approveCommandCoverageShrinkage,
        CancellationToken cancellationToken)
    {
        foreach (var htmlScraper in _htmlScrapers)
        {
            if (!ShouldProcess(htmlScraper.ToolName, toolList))
            {
                _logger.LogInformation("Skipping {Tool}", htmlScraper.ToolName);
                continue;
            }

            if (!processedTools.Add(htmlScraper.ToolName))
            {
                continue;
            }

            result.ToolsProcessed.Add(htmlScraper.ToolName);
            await ProcessHtmlScraperAsync(
                htmlScraper,
                cliScrapersByTool,
                outputDirectory,
                result,
                emittedPaths,
                fileSystemPathComparer,
                useCliFirst,
                approveCommandCoverageShrinkage,
                cancellationToken);
        }
    }

    private async Task ProcessHtmlScraperAsync(
        ICliDocumentationScraper htmlScraper,
        IReadOnlyDictionary<string, ICliScraper> cliScrapersByTool,
        string outputDirectory,
        GenerationResult result,
        HashSet<string> emittedPaths,
        StringComparer fileSystemPathComparer,
        bool useCliFirst,
        bool approveCommandCoverageShrinkage,
        CancellationToken cancellationToken)
    {
        _logger.LogInformation("Processing {Tool}...", htmlScraper.ToolName);

        try
        {
            if (useCliFirst && cliScrapersByTool.TryGetValue(htmlScraper.ToolName, out var cliScraper))
            {
                var cliFailureReason = await GenerateFromCliAsync(
                    cliScraper,
                    outputDirectory,
                    result,
                    emittedPaths,
                    fileSystemPathComparer,
                    approveCommandCoverageShrinkage,
                    cancellationToken);
                if (cliFailureReason is null)
                {
                    return;
                }

                _logger.LogWarning("{Reason} Falling back to HTML scraper.", cliFailureReason);
            }

            await GenerateFromHtmlAsync(
                htmlScraper,
                outputDirectory,
                result,
                emittedPaths,
                fileSystemPathComparer,
                approveCommandCoverageShrinkage,
                cancellationToken);
        }
        catch (Exception ex)
        {
            AddScrapingError(result, htmlScraper.ToolName, ex, cliOnly: false);
        }
    }

    private async Task GenerateFromHtmlAsync(
        ICliDocumentationScraper htmlScraper,
        string outputDirectory,
        GenerationResult result,
        HashSet<string> emittedPaths,
        StringComparer fileSystemPathComparer,
        bool approveCommandCoverageShrinkage,
        CancellationToken cancellationToken)
    {
        _logger.LogInformation("Using HTML scraper for {Tool}", htmlScraper.ToolName);
        var toolDefinition = await htmlScraper.ScrapeAsync(cancellationToken);

        if (toolDefinition.Errors.Count > 0)
        {
            result.Errors.AddRange(toolDefinition.Errors);
            _logger.LogWarning(
                "Encountered {Count} errors while scraping {Tool}",
                toolDefinition.Errors.Count,
                htmlScraper.ToolName);
        }

        _logger.LogInformation(
            "Scraped {Count} commands for {Tool}",
            toolDefinition.Commands.Count,
            htmlScraper.ToolName);
        toolDefinition = await EnhanceTypesAsync(toolDefinition, htmlScraper.ToolName, cancellationToken);

        await GenerateForToolAsync(
            toolDefinition,
            outputDirectory,
            result,
            emittedPaths,
            fileSystemPathComparer,
            approveCommandCoverageShrinkage,
            cancellationToken);

        _logger.LogInformation("Generated files for {Tool}", htmlScraper.ToolName);
    }

    private async Task<CliToolDefinition> EnhanceTypesAsync(
        CliToolDefinition toolDefinition,
        string toolName,
        CancellationToken cancellationToken)
    {
        if (_typeEnhancer is null)
        {
            return toolDefinition;
        }

        _logger.LogInformation("Enhancing types for {Tool} using CLI help...", toolName);
        try
        {
            var enhanced = await _typeEnhancer.EnhanceAsync(toolDefinition, cancellationToken);
            _logger.LogInformation("Type enhancement complete for {Tool}", toolName);
            return enhanced;
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Type enhancement failed for {Tool}, using scraped types", toolName);
            return toolDefinition;
        }
    }

    private async Task ProcessCliOnlyScrapersAsync(
        List<string> toolList,
        ISet<string> processedTools,
        string outputDirectory,
        GenerationResult result,
        HashSet<string> emittedPaths,
        StringComparer fileSystemPathComparer,
        bool useCliFirst,
        bool approveCommandCoverageShrinkage,
        CancellationToken cancellationToken)
    {
        if (!useCliFirst)
        {
            return;
        }

        foreach (var cliScraper in _cliScrapers)
        {
            if (processedTools.Contains(cliScraper.ToolName))
            {
                continue;
            }

            if (!ShouldProcess(cliScraper.ToolName, toolList))
            {
                _logger.LogInformation("Skipping CLI-only tool {Tool}", cliScraper.ToolName);
                continue;
            }

            processedTools.Add(cliScraper.ToolName);
            result.ToolsProcessed.Add(cliScraper.ToolName);
            await ProcessCliOnlyScraperAsync(
                cliScraper,
                outputDirectory,
                result,
                emittedPaths,
                fileSystemPathComparer,
                approveCommandCoverageShrinkage,
                cancellationToken);
        }
    }

    private async Task ProcessCliOnlyScraperAsync(
        ICliScraper cliScraper,
        string outputDirectory,
        GenerationResult result,
        HashSet<string> emittedPaths,
        StringComparer fileSystemPathComparer,
        bool approveCommandCoverageShrinkage,
        CancellationToken cancellationToken)
    {
        _logger.LogInformation("Processing CLI-only tool {Tool}...", cliScraper.ToolName);

        try
        {
            var failureReason = await GenerateFromCliAsync(
                cliScraper,
                outputDirectory,
                result,
                emittedPaths,
                fileSystemPathComparer,
                approveCommandCoverageShrinkage,
                cancellationToken);
            if (failureReason is not null)
            {
                throw new InvalidOperationException(
                    $"{failureReason} This is a CLI-only tool with no HTML fallback.");
            }
        }
        catch (Exception ex)
        {
            AddScrapingError(result, cliScraper.ToolName, ex, cliOnly: true);
        }
    }

    private void AddScrapingError(
        GenerationResult result,
        string toolName,
        Exception exception,
        bool cliOnly)
    {
        _logger.LogError(
            exception,
            cliOnly ? "Failed to process CLI-only tool {Tool}" : "Failed to process {Tool}",
            toolName);
        result.Errors.Add(new ScrapingError
        {
            Source = toolName,
            Message = exception.Message,
            Exception = exception,
        });
    }

    /// <summary>
    /// Scrapes a tool via its CLI scraper and generates code for it.
    /// Returns null when generation completed, or a failure reason when it could not run.
    /// Failure policy belongs to the caller: the HTML-scraper loop falls back, the
    /// CLI-only loop throws.
    /// </summary>
    private async Task<string?> GenerateFromCliAsync(
        ICliScraper cliScraper,
        string outputDirectory,
        GenerationResult result,
        HashSet<string> emittedPaths,
        StringComparer fileSystemPathComparer,
        bool approveCommandCoverageShrinkage,
        CancellationToken cancellationToken)
    {
        if (!await cliScraper.IsAvailableAsync(cancellationToken))
        {
            return $"The {cliScraper.ToolName} CLI is not available on PATH - check the tool's install step.";
        }

        _logger.LogInformation("Using CLI scraper for {Tool}", cliScraper.ToolName);

        var allCommands = new List<CliCommandDefinition>();

        await foreach (var command in cliScraper.ScrapeAsync(cancellationToken))
        {
            // Fail the tool before any generators run. Skipping an invalid command here
            // could silently delete an existing generated API during stale-file cleanup.
            command.ValidateOperandCoverage();
            allCommands.Add(command);
        }

        var toolDefinition = cliScraper.CreateToolDefinition();
        var toolVersion = await cliScraper.GetVersionAsync(cancellationToken);

        _logger.LogInformation("Scraped {Count} commands for {Tool}", allCommands.Count, cliScraper.ToolName);

        if (allCommands.Count == 0)
        {
            // The CLI is present (IsAvailableAsync passed), so "not installed" is not the
            // problem - the scraper failed to parse anything out of the help output.
            return $"The {cliScraper.ToolName} CLI reported itself available but help scraping produced no commands. " +
                   "Check the scraper's help-text parsing against the currently installed CLI version.";
        }

        var completeToolDefinition = toolDefinition with
        {
            Commands = allCommands,
            ToolVersion = toolVersion,
            Errors = [],
        };
        if (_typeEnhancer is not null)
        {
            completeToolDefinition = await _typeEnhancer
                .EnhanceManualOverridesAsync(completeToolDefinition, cancellationToken);
        }

        await GenerateForToolAsync(
            completeToolDefinition,
            outputDirectory,
            result,
            emittedPaths,
            fileSystemPathComparer,
            approveCommandCoverageShrinkage,
            cancellationToken);

        _logger.LogInformation("Generated files for {Tool} ({Count} commands, {SubDomainCount} sub-domains)",
            cliScraper.ToolName, allCommands.Count, completeToolDefinition.SubDomainGroups.Count);

        return null;
    }

    /// <summary>
    /// Runs all generators for a tool and writes the results to disk.
    /// All files are generated in memory and validated for path collisions before anything
    /// on disk is touched, so a scraping or generation failure never mutates the package.
    /// Writes happen before stale files are pruned, so nothing is ever deleted until its
    /// replacement exists on disk - an I/O failure mid-write leaves the old files in
    /// place (possibly alongside new ones, which the compile check then catches).
    /// </summary>
    private async Task GenerateForToolAsync(
        CliToolDefinition tool,
        string outputDirectory,
        GenerationResult result,
        HashSet<string> emittedPaths,
        StringComparer fileSystemPathComparer,
        bool approveCommandCoverageShrinkage,
        CancellationToken cancellationToken,
        bool enforceOutputContainment = false,
        bool cleanupGeneratedFilesByNamespacePrefix = true,
        bool writeAssemblyInfo = true,
        string? commandCoverageBaselinePath = null,
        StringComparer? commandCoveragePathComparer = null,
        bool allowMissingCommandCoverageManifest = false,
        IReadOnlySet<string>? replaceableExistingPaths = null,
        IReadOnlyDictionary<string, string>? enumBaselinePaths = null,
        Func<IReadOnlyCollection<string>, CancellationToken, Task>? beforeWrite = null)
    {
        var globalOptions = tool.GetGlobalOptions();
        var normalizedCommands = GeneratorUtils.NormalizeCommandClassNames(tool.Commands);
        var normalizedTool = tool with
        {
            Commands = normalizedCommands,
            GlobalOptions = globalOptions,
            SupplementalGlobalOptions = [],
        };
        var collisionResolvedTool = InheritedPropertyCollisionResolver.Resolve(normalizedTool);
        var toolDefinition = ExecutablePrerequisiteCatalog.PrepareForGeneration(collisionResolvedTool);
        var resolvedGlobalOptions = toolDefinition.GetGlobalOptions();
        foreach (var command in toolDefinition.Commands)
        {
            ExternalToolDefinitionLoader.ValidateCompatibilityMetadata(command, resolvedGlobalOptions);
        }

        if (enforceOutputContainment)
        {
            ValidateToolOutputContainment(toolDefinition, outputDirectory);
        }

        toolDefinition = EnumDefinitionStabilizer.Stabilize(
            toolDefinition,
            outputDirectory,
            enumBaselinePaths);
        var generatedFiles = toolDefinition.GenerateCode
            ? await GenerateFilesAsync(toolDefinition, cancellationToken).ConfigureAwait(false)
            : [];

        GeneratorUtils.EnsureNoDuplicateFilePaths(generatedFiles, emittedPaths);

        if (enforceOutputContainment)
        {
            ValidateGeneratedOutputContainment(
                toolDefinition,
                generatedFiles,
                outputDirectory,
                replaceableExistingPaths);
        }

        var coverage = CommandCoverageGuard.Evaluate(
            toolDefinition,
            outputDirectory,
            approveCommandCoverageShrinkage,
            commandCoverageBaselinePath,
            commandCoveragePathComparer,
            allowMissingCommandCoverageManifest);
        result.CommandCoverage.Add(coverage);

        if (coverage.Violations.Count > 0)
        {
            throw new InvalidOperationException(
                $"Command coverage validation failed for {tool.ToolName}:{Environment.NewLine}"
                    + string.Join(Environment.NewLine, coverage.Violations.Select(violation => $"- {violation}")));
        }

        if (beforeWrite is not null)
        {
            var candidateOwnedPaths = generatedFiles
                .Select(file => file.RelativePath)
                .Append(Path.GetRelativePath(outputDirectory, coverage.ManifestPath))
                .ToArray();
            await beforeWrite(candidateOwnedPaths, cancellationToken);
        }

        var writtenFullPaths = new HashSet<string>(fileSystemPathComparer);

        foreach (var file in generatedFiles)
        {
            var fullPath = Path.Combine(outputDirectory, file.RelativePath);
            await WriteFileAsync(
                fullPath,
                file.Content,
                cancellationToken,
                enforceOutputContainment ? outputDirectory : null,
                "generated file path");
            writtenFullPaths.Add(Path.GetFullPath(fullPath));
            result.FilesGenerated.Add(file.RelativePath);
            emittedPaths.Add(file.RelativePath.Replace('\\', '/'));
        }

        // Only after every replacement is on disk is it safe to prune stale files.
        // External generation reconciles only its recorded ownership after this method returns.
        if (toolDefinition.GenerateCode && cleanupGeneratedFilesByNamespacePrefix)
        {
            CleanupGeneratedFiles(
                outputDirectory,
                toolDefinition.OutputDirectory,
                toolDefinition.NamespacePrefix,
                writtenFullPaths,
                result.FilesDeleted);
        }

        await CommandCoverageGuard.WriteManifestAsync(
            coverage,
            cancellationToken,
            enforceOutputContainment ? outputDirectory : null);
        result.FilesGenerated.Add(Path.GetRelativePath(outputDirectory, coverage.ManifestPath));

        if (toolDefinition.GenerateCode && writeAssemblyInfo)
        {
            await WriteAssemblyInfoAsync(
                outputDirectory,
                toolDefinition,
                cancellationToken,
                enforceOutputContainment).ConfigureAwait(false);
            result.FilesGenerated.Add(
                Path.Combine(toolDefinition.OutputDirectory, "AssemblyInfo.Generated.cs"));
        }
    }

    private static void ValidateToolOutputContainment(
        CliToolDefinition toolDefinition,
        string outputDirectory)
    {
        foreach (var cleanupDirectory in GeneratedCleanupDirectories)
        {
            ValidateContainedPath(
                outputDirectory,
                Path.Combine(toolDefinition.OutputDirectory, cleanupDirectory),
                "generated cleanup directory");
        }

        ValidateContainedPath(
            outputDirectory,
            Path.Combine(
                toolDefinition.OutputDirectory,
                "Generated",
                $"{toolDefinition.NamespacePrefix}.CommandCoverage.json"),
            "command coverage manifest");
    }

    private static void ValidateGeneratedOutputContainment(
        CliToolDefinition toolDefinition,
        IReadOnlyCollection<GeneratedFile> generatedFiles,
        string outputDirectory,
        IReadOnlySet<string>? replaceableExistingPaths)
    {
        foreach (var file in generatedFiles)
        {
            var fullPath = ValidateContainedPath(
                outputDirectory,
                file.RelativePath,
                "generated file path");
            RejectUnownedExistingPath(fullPath, replaceableExistingPaths);
        }

        RejectUnownedExistingPath(
            ValidateContainedPath(
                outputDirectory,
                CommandCoverageGuard.GetManifestPath(toolDefinition, outputDirectory),
                "command coverage manifest"),
            replaceableExistingPaths);
    }

    private async Task<List<GeneratedFile>> GenerateFilesAsync(
        CliToolDefinition toolDefinition,
        CancellationToken cancellationToken)
    {
        var generatedFiles = new List<GeneratedFile>();
        foreach (var generator in _generators)
        {
            generatedFiles.AddRange(
                await generator.GenerateAsync(toolDefinition, cancellationToken).ConfigureAwait(false));
        }

        return generatedFiles;
    }

    private static List<string> ParseToolList(string tools)
    {
        if (string.Equals(tools, "all", StringComparison.OrdinalIgnoreCase))
        {
            return [];
        }

        return tools.Split(',', StringSplitOptions.RemoveEmptyEntries)
            .Select(t => t.Trim().ToLowerInvariant())
            .ToList();
    }

    private static bool ShouldProcess(string toolName, List<string> toolList)
    {
        if (toolList.Count == 0)
        {
            return true; // Process all
        }

        return toolList.Contains(toolName.ToLowerInvariant());
    }

    private static async Task WriteFileAsync(
        string path,
        string content,
        CancellationToken cancellationToken,
        string? containmentRoot = null,
        string propertyName = "generated path")
    {
        if (containmentRoot is not null)
        {
            ValidateContainedPath(containmentRoot, path, propertyName);
        }

        var directory = Path.GetDirectoryName(path);
        if (!string.IsNullOrEmpty(directory))
        {
            Directory.CreateDirectory(directory);
        }

        if (containmentRoot is not null)
        {
            ValidateContainedPath(containmentRoot, path, propertyName);
        }

        await File.WriteAllTextAsync(path, content, cancellationToken);
    }

    private static string ValidateContainedPath(
        string outputDirectory,
        string path,
        string propertyName)
    {
        var relativePath = Path.IsPathRooted(path)
            ? Path.GetRelativePath(outputDirectory, path)
            : path;
        return ExternalToolDefinitionLoader.ValidateRelativeOutputPath(
            relativePath,
            outputDirectory,
            propertyName);
    }

    private static void RejectUnownedExistingPath(
        string fullPath,
        IReadOnlySet<string>? replaceableExistingPaths)
    {
        if (File.Exists(fullPath)
            && (replaceableExistingPaths is null
                || !replaceableExistingPaths.Contains(Path.GetFullPath(fullPath))))
        {
            throw new InvalidDataException(
                $"Refusing to overwrite existing path '{fullPath}' because it is not owned by this external definition.");
        }
    }

    private void CleanupReconciledGeneratedFiles(
        string outputDirectory,
        IReadOnlyCollection<string> registeredToolNames,
        ICollection<string> deletedPaths)
    {
        foreach (var provider in _generators.OfType<IGeneratedFileCleanupProvider>())
        {
            foreach (var rule in provider.GetCleanupRules(registeredToolNames))
            {
                var directory = Path.Combine(outputDirectory, rule.RelativeDirectory);
                if (!Directory.Exists(directory))
                {
                    continue;
                }

                foreach (var file in Directory.GetFiles(directory, rule.SearchPattern, SearchOption.TopDirectoryOnly))
                {
                    if (rule.ExpectedFileNames.Contains(Path.GetFileName(file)) || !FileContainsMarker(file, rule.GeneratedMarker))
                    {
                        continue;
                    }

                    DeleteFileAndRecord(outputDirectory, file, deletedPaths);
                }
            }
        }
    }

    private static bool FileContainsMarker(
        string filePath,
        string marker,
        string? containmentRoot = null)
    {
        if (containmentRoot is not null)
        {
            ValidateContainedPath(containmentRoot, filePath, "generated file cleanup");
        }

        using var reader = new StreamReader(filePath);
        for (var lineNumber = 0; lineNumber < 10 && reader.ReadLine() is { } line; lineNumber++)
        {
            if (line.Contains(marker, StringComparison.Ordinal))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Generates and writes AssemblyInfo.Generated.cs with generation metadata.
    /// This centralizes generation metadata in one file per assembly rather than in every
    /// generated file, reducing unnecessary diffs when regenerating unchanged files.
    /// </summary>
    private static async Task WriteAssemblyInfoAsync(
        string outputDirectory,
        CliToolDefinition toolDefinition,
        CancellationToken cancellationToken,
        bool enforceOutputContainment)
    {
        var content = GeneratorUtils.GenerateAssemblyInfo(toolDefinition.TargetNamespace);
        var path = Path.Combine(outputDirectory, toolDefinition.OutputDirectory, "AssemblyInfo.Generated.cs");
        await WriteFileAsync(
            path,
            content,
            cancellationToken,
            enforceOutputContainment ? outputDirectory : null,
            "generated assembly metadata");
    }

    /// <summary>
    /// Prunes stale generated files after the current generation has been written.
    /// Only deletes files that match the namespace prefix to avoid removing files from other tools
    /// that share the same output directory (e.g., kubectl and kustomize in ModularPipelines.Kubernetes).
    /// Files just written this run (<paramref name="pathsToKeep"/>) and files without the
    /// auto-generated header (hand-written) are never deleted.
    /// </summary>
    private void CleanupGeneratedFiles(
        string outputDirectory,
        string toolOutputDirectory,
        string namespacePrefix,
        IReadOnlySet<string> pathsToKeep,
        ICollection<string> deletedPaths)
    {
        var toolPath = Path.Combine(outputDirectory, toolOutputDirectory);
        if (!Directory.Exists(toolPath))
        {
            return;
        }

        foreach (var subDir in GeneratedCleanupDirectories)
        {
            var subDirPath = Path.Combine(toolPath, subDir);
            if (!Directory.Exists(subDirPath))
            {
                continue;
            }

            // Delete *.Generated.cs files that match the namespace prefix
            // This ensures we don't delete files from other tools sharing the same directory
            // (e.g., running kustomize won't delete KubernetesOptions.Generated.cs which kubectl needs)
            var generatedFiles = Directory.GetFiles(subDirPath, "*.Generated.cs", SearchOption.TopDirectoryOnly);
            foreach (var file in generatedFiles)
            {
                if (pathsToKeep.Contains(Path.GetFullPath(file)))
                {
                    continue; // Written this run - not stale
                }

                var fileName = Path.GetFileName(file);
                if (FileMatchesNamespacePrefix(fileName, namespacePrefix)
                    && IsAutoGeneratedFile(file))
                {
                    DeleteFileAndRecord(outputDirectory, file, deletedPaths);
                }
            }

            // Also clean up legacy files that were auto-generated before the .Generated.cs
            // naming convention. The auto-generated header marker is required - files
            // without it are hand-written and must never be deleted by the generator.
            var allCsFiles = Directory.GetFiles(subDirPath, "*.cs", SearchOption.TopDirectoryOnly);
            foreach (var file in allCsFiles)
            {
                if (file.EndsWith(".Generated.cs", StringComparison.OrdinalIgnoreCase))
                {
                    continue; // Already handled above
                }

                var fileName = Path.GetFileName(file);

                if (FileMatchesNamespacePrefix(fileName, namespacePrefix) && IsAutoGeneratedFile(file))
                {
                    DeleteFileAndRecord(outputDirectory, file, deletedPaths);
                }
            }
        }

        CleanupLegacyGeneratedLayout(
            outputDirectory,
            toolPath,
            namespacePrefix,
            deletedPaths);

        _logger.LogInformation("Cleaned up old files matching prefix '{Prefix}' in {Path}", namespacePrefix, toolPath);
    }

    private void CleanupLegacyGeneratedLayout(
        string outputDirectory,
        string toolPath,
        string namespacePrefix,
        ICollection<string> deletedPaths)
    {
        var legacyGeneratedPath = Path.Combine(toolPath, "Generated");

        foreach (var subDir in GeneratedCleanupDirectories)
        {
            var subDirPath = Path.Combine(legacyGeneratedPath, subDir);
            if (!Directory.Exists(subDirPath))
            {
                continue;
            }

            foreach (var file in Directory.GetFiles(subDirPath, "*.cs", SearchOption.AllDirectories))
            {
                if (FileMatchesNamespacePrefix(Path.GetFileName(file), namespacePrefix)
                    && IsAutoGeneratedFile(file, outputDirectory))
                {
                    DeleteFileAndRecord(
                        outputDirectory,
                        file,
                        deletedPaths,
                        validateContainment: true);
                }
            }
        }
    }

    /// <summary>
    /// Checks if a file name matches the given namespace prefix.
    /// Handles special cases like "Extensions" suffix (e.g., "DockerExtensions.cs" matches "Docker")
    /// and interface naming (e.g., "IDocker.cs" matches "Docker").
    /// </summary>
    private static bool FileMatchesNamespacePrefix(string fileName, string namespacePrefix)
    {
        // Direct prefix match (e.g., "HelmInstallOptions.Generated.cs" matches "Helm")
        if (fileName.StartsWith(namespacePrefix, StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        // Check for interface naming pattern (e.g., "IDocker.cs" or "IDocker.Generated.cs" should match "Docker")
        // The generator creates I{Prefix}.Generated.cs files
        var interfaceName = $"I{namespacePrefix}";
        if (fileName.StartsWith(interfaceName, StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        // Check for Extensions class naming pattern (e.g., "DockerExtensions.cs" should match "Docker")
        // The generator creates {Prefix}Extensions.cs files
        var extensionsName = $"{namespacePrefix}Extensions";
        if (fileName.StartsWith(extensionsName, StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        return false;
    }

    /// <summary>
    /// Checks if a file contains the auto-generated header marker.
    /// </summary>
    private static bool IsAutoGeneratedFile(
        string filePath,
        string? containmentRoot = null)
    {
        try
        {
            if (containmentRoot is not null)
            {
                ValidateContainedPath(containmentRoot, filePath, "generated file cleanup");
            }

            // Read first few lines to check for auto-generated marker
            using var reader = new StreamReader(filePath);
            for (var i = 0; i < 5 && !reader.EndOfStream; i++)
            {
                var line = reader.ReadLine();
                if (line != null && line.Contains("<auto-generated>", StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }
            return false;
        }
        catch
        {
            return false;
        }
    }

    private bool DeleteFileAndRecord(
        string outputDirectory,
        string file,
        ICollection<string> deletedPaths,
        bool validateContainment = false)
    {
        if (validateContainment)
        {
            ValidateContainedPath(outputDirectory, file, "generated file cleanup");
        }

        try
        {
            File.Delete(file);
            deletedPaths.Add(Path.GetRelativePath(outputDirectory, file));
            _logger.LogDebug("Deleted old generated file: {File}", file);
            return true;
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Failed to delete file: {File}", file);
            return false;
        }
    }

    private sealed record ExternalOwnershipManifest(
        string RelativePath,
        string? OwnershipId,
        IReadOnlyList<string> OwnedPaths,
        bool Exists);
}

/// <summary>
/// Result of the code generation process.
/// </summary>
public class GenerationResult
{
    public List<string> ToolsProcessed { get; } = [];
    public List<string> FilesGenerated { get; } = [];
    public List<string> FilesDeleted { get; } = [];
    public List<ScrapingError> Errors { get; } = [];

    internal List<CommandCoverageEvaluation> CommandCoverage { get; } = [];

    public IEnumerable<string> ChangedPaths => FilesGenerated
        .Concat(FilesDeleted)
        .Select(path => path.Replace('\\', '/'))
        .Distinct(StringComparer.OrdinalIgnoreCase);

    public bool HasErrors => Errors.Count > 0;

    public string GetSummary()
    {
        var summary = $"""
            Generation Summary:
            - Tools processed: {ToolsProcessed.Count} ({string.Join(", ", ToolsProcessed)})
            - Files generated: {FilesGenerated.Count}
            - Errors: {Errors.Count}
            """;

        if (CommandCoverage.Count == 0)
        {
            return summary;
        }

        return summary + Environment.NewLine + GetCommandCoverageSummary();
    }

    private string GetCommandCoverageSummary()
    {
        var lines = new List<string> { "Command coverage report:" };

        foreach (var coverage in CommandCoverage.OrderBy(item => item.Manifest.ToolName, StringComparer.OrdinalIgnoreCase))
        {
            var version = coverage.Manifest.ToolVersion ?? "unknown version";
            lines.Add(
                $"- {coverage.Manifest.ToolName} ({version}): {coverage.Manifest.CommandCount} commands, "
                + $"tree {coverage.Manifest.CommandTreeSha256}");

            if (!coverage.HasPreviousBaseline)
            {
                lines.Add("  - Baseline: created");
            }

            AppendDiff(lines, "Added", coverage.AddedCommands);
            AppendDiff(lines, coverage.ShrinkageApproved ? "Removed (approved)" : "Removed", coverage.RemovedCommands);
            AppendDiff(lines, "Groups without children", coverage.KnownGroupsWithoutChildren);
            AppendDiff(
                lines,
                "Excluded",
                coverage.Manifest.Exclusions
                    .Select(exclusion => $"{exclusion.Command} ({exclusion.Reason})")
                    .ToArray());
            AppendDiff(lines, "Violations", coverage.Violations);
        }

        return string.Join(Environment.NewLine, lines);
    }

    private static void AppendDiff(List<string> lines, string label, IReadOnlyList<string> values)
    {
        if (values.Count == 0)
        {
            return;
        }

        const int displayLimit = 50;
        var displayed = values.Take(displayLimit);
        var suffix = values.Count > displayLimit ? $" (+{values.Count - displayLimit} more; see manifest)" : string.Empty;
        lines.Add($"  - {label}: {string.Join(", ", displayed)}{suffix}");
    }
}
