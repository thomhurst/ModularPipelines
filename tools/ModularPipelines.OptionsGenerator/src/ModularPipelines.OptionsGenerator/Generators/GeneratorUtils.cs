    /// <summary>
    /// Generates a C# method name from CLI command parts.
    /// Converts command parts to PascalCase method name.
    /// E.g., ["container", "create"] -> "ContainerCreate", ["build-server"] -> "BuildServer"
    /// Returns "Execute" for empty command parts (single-command tools like ansible).
    /// </summary>
    /// <param name="commandParts">The command parts array.</param>
    /// <returns>The method name in PascalCase, or "Execute" if command parts is empty.</returns>
    public static string GenerateMethodNameFromCommandParts(string[] commandParts)
    {
        if (commandParts.Length == 0)
        {
            return "Execute";
        }

        return string.Join("", commandParts.Select(ToPascalCase));
    }

    /// <summary>
    /// Generates a C# method name from the last part of a CLI command.
    /// Used for sub-domain commands where the method name is derived from the last segment.
    /// E.g., ["network", "create"] uses "create" -> "Create"
    /// </summary>
    /// <param name="command">The CLI command definition.</param>
    /// <returns>The method name in PascalCase, or "Execute" if no command parts.</returns>
    public static string GenerateMethodNameFromLastCommandPart(CliCommandDefinition command)
    {
        if (command.CommandParts.Length == 0)
        {
            return "Execute";
        }

        return ToPascalCase(command.CommandParts[^1]);
    }

    /// <summary>
    /// The executionOptions parameter as emitted in every generated command method.
    /// </summary>
    public const string ExecutionOptionsParameter = "CommandExecutionOptions? executionOptions = null";

    /// <summary>
    /// Whether a command has required members that must be constructor/method parameters.
    /// </summary>
    public static bool HasRequiredParameters(CliCommandDefinition command)
    {
        ArgumentNullException.ThrowIfNull(command);

        return command.RequiredOptions.Count > 0 ||
               command.PositionalArguments.Any(p => p.IsRequired);
    }

    internal static IReadOnlyList<RequiredConstructorParameter> GetRequiredConstructorParameters(
        CliCommandDefinition command)
    {
        ArgumentNullException.ThrowIfNull(command);

        return GetRequiredConstructorParameters(
            command,
            CliPositionalArgument.MergeDuplicates(command.PositionalArguments));
    }

    internal static IReadOnlyList<RequiredConstructorParameter> GetRequiredConstructorParameters(
        CliCommandDefinition command,
        IReadOnlyList<CliPositionalArgument> positionalArguments)
    {
        ArgumentNullException.ThrowIfNull(command);
        ArgumentNullException.ThrowIfNull(positionalArguments);

        var parameters = command.RequiredOptions
            .Select(option => new RequiredConstructorParameter(
                option.PropertyName,
                option.CSharpType,
                option.IsSecret,
                option,
                null))
            .ToList();
        var existingNames = parameters
            .Select(parameter => parameter.PropertyName)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        parameters.AddRange(positionalArguments
            .Where(argument => argument.IsRequired)
            .Where(argument => existingNames.Add(argument.PropertyName))
            .Select(argument => new RequiredConstructorParameter(
                argument.PropertyName,
                argument.CSharpType,
                argument.IsSecret,
                null,
                argument)));

        return parameters;
    }

    /// <summary>
    /// Builds the options parameter for a generated command method. Shared by the
    /// interface and implementation generators so their signatures can never diverge.
    /// Optional options must be nullable: generated files declare #nullable enable, so a
    /// null default on a non-nullable reference type produces CS8625.
    /// </summary>
    public static string BuildOptionsParameter(CliCommandDefinition command)
    {
        return HasRequiredParameters(command)
            ? $"{command.ClassName} options"
            : $"{command.ClassName}? options = null";
    }

    /// <summary>
    /// Generates a command method signature for a service interface.
    /// </summary>
    public static void GenerateServiceMethodSignature(
        StringBuilder sb,
        string methodName,
        CliCommandDefinition command,
        string indent = "    ")
    {
        ArgumentNullException.ThrowIfNull(sb);
        ArgumentNullException.ThrowIfNull(command);
        methodName = EnsureAsyncSuffix(methodName);

        if (!string.IsNullOrEmpty(command.Description))
        {
            GenerateXmlDocumentation(sb, command.Description, indent);
            sb.AppendLine($"{indent}/// <param name=\"options\">The command options.</param>");
            sb.AppendLine($"{indent}/// <param name=\"executionOptions\">The execution configuration options.</param>");
            sb.AppendLine($"{indent}/// <param name=\"cancellationToken\">Cancellation token.</param>");
            sb.AppendLine($"{indent}/// <returns>The command result.</returns>");
        }

        sb.AppendLine($"{indent}Task<CommandResult> {methodName}({BuildOptionsParameter(command)}, {ExecutionOptionsParameter}, CancellationToken cancellationToken = default);");

        foreach (var compatibilityMethod in GetCompatibilityMethods(command, methodName))
        {
            sb.AppendLine();
            sb.AppendLine(
                $"{indent}[Obsolete({FormatStringLiteral(compatibilityMethod.ObsoleteMessage)})]");
            sb.AppendLine($"{indent}Task<CommandResult> {compatibilityMethod.MethodName}({BuildOptionsParameter(command)}, {ExecutionOptionsParameter}, CancellationToken cancellationToken = default);");
        }
    }

    /// <summary>
    /// Generates a service method that executes a CLI command.
    /// Used by ServiceImplementationGenerator and SubDomainClassGenerator to avoid duplication.
    /// </summary>
    /// <param name="sb">The StringBuilder to append to.</param>
    /// <param name="methodName">The name of the method to generate.</param>
    /// <param name="command">The CLI command definition.</param>
    /// <param name="includeXmlDoc">Whether to include XML documentation.</param>
    /// <param name="indent">The indentation string (defaults to 4 spaces).</param>
    public static void GenerateServiceMethod(
        StringBuilder sb,
        string methodName,
        CliCommandDefinition command,
        bool includeXmlDoc = true,
        string indent = "    ")
    {
        ArgumentNullException.ThrowIfNull(sb);
        ArgumentNullException.ThrowIfNull(command);
        methodName = EnsureAsyncSuffix(methodName);

        var hasRequiredParams = HasRequiredParameters(command);

        // XML documentation
        if (includeXmlDoc && !string.IsNullOrEmpty(command.Description))
        {
            GenerateXmlDocumentation(sb, command.Description, indent);
            sb.AppendLine($"{indent}/// <param name=\"options\">The command options.</param>");
            sb.AppendLine($"{indent}/// <param name=\"executionOptions\">The execution configuration options.</param>");
            sb.AppendLine($"{indent}/// <param name=\"cancellationToken\">Cancellation token.</param>");
            sb.AppendLine($"{indent}/// <returns>The command result.</returns>");
        }
        else
        {
            sb.AppendLine($"{indent}/// <inheritdoc />");
        }

        sb.AppendLine($"{indent}public virtual async Task<CommandResult> {methodName}(");
        sb.AppendLine($"{indent}    {BuildOptionsParameter(command)},");
        sb.AppendLine($"{indent}    {ExecutionOptionsParameter},");
        sb.AppendLine($"{indent}    CancellationToken cancellationToken = default)");
        sb.AppendLine($"{indent}{{");

        if (hasRequiredParams)
        {
            sb.AppendLine($"{indent}    return await _command.ExecuteCommandLineToolAsync(options, executionOptions, cancellationToken);");
        }
        else
        {
            sb.AppendLine($"{indent}    return await _command.ExecuteCommandLineToolAsync(options ?? new {command.ClassName}(), executionOptions, cancellationToken);");
        }

        sb.AppendLine($"{indent}}}");

        foreach (var compatibilityMethod in GetCompatibilityMethods(command, methodName))
        {
            sb.AppendLine();
            GenerateCompatibilityServiceMethod(
                sb,
                compatibilityMethod,
                methodName,
                command,
                indent);
        }
    }

    /// <summary>
    /// Adds the standard asynchronous method suffix when it is not already present.
    /// </summary>
    /// <param name="methodName">The generated method name.</param>
    /// <returns>The method name ending in <c>Async</c>.</returns>
    public static string EnsureAsyncSuffix(string methodName)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(methodName);

        return methodName.EndsWith("Async", StringComparison.Ordinal)
            ? methodName
            : $"{methodName}Async";
    }

    internal static IEnumerable<CliCompatibilityMethod> GetCompatibilityMethods(
        CliCommandDefinition command,
        string currentMethodName)
    {
        return command.CompatibilityMethods
            .Select(method => method with
            {
                MethodName = EnsureAsyncSuffix(method.MethodName),
                ObsoleteMessage = EnsureAsyncCompatibilityMessage(
                    method.ObsoleteMessage,
                    currentMethodName),
            })
            .Where(method => !string.Equals(method.MethodName, currentMethodName, StringComparison.Ordinal))
            .DistinctBy(method => method.MethodName, StringComparer.Ordinal);
    }

    private static string EnsureAsyncCompatibilityMessage(
        string obsoleteMessage,
        string currentMethodName)
    {
        const string asyncSuffix = "Async";
        if (!currentMethodName.EndsWith(asyncSuffix, StringComparison.Ordinal))
        {
            return obsoleteMessage;
        }

        if (obsoleteMessage.Contains(currentMethodName, StringComparison.Ordinal))
        {
            return obsoleteMessage;
        }

        var unsuffixedMethodName = currentMethodName[..^asyncSuffix.Length];
        return obsoleteMessage.Replace(
            unsuffixedMethodName,
            currentMethodName,
            StringComparison.Ordinal);
    }

    private static void GenerateCompatibilityServiceMethod(
        StringBuilder sb,
        CliCompatibilityMethod compatibilityMethod,
        string currentMethodName,
        CliCommandDefinition command,
        string indent)
    {
        sb.AppendLine(
            $"{indent}[Obsolete({FormatStringLiteral(compatibilityMethod.ObsoleteMessage)})]");
        sb.AppendLine($"{indent}public virtual async Task<CommandResult> {compatibilityMethod.MethodName}(");
        sb.AppendLine($"{indent}    {BuildOptionsParameter(command)},");
        sb.AppendLine($"{indent}    {ExecutionOptionsParameter},");
        sb.AppendLine($"{indent}    CancellationToken cancellationToken = default)");
        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}    return await {currentMethodName}(options, executionOptions, cancellationToken);");
        sb.AppendLine($"{indent}}}");
    }

