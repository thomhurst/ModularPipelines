    internal static string GenerateSecretAttribute(CliOptionDefinition option)
    {
        if (option.SecretValueKeys.Count == 0)
        {
            return "SecretValue";
        }

        var keys = option.SecretValueKeys.Select(FormatStringLiteral);
        return $"SecretValue({string.Join(", ", keys)})";
    }

    /// <summary>
    /// Escapes text for use in XML documentation comments.
    /// </summary>
    public static string EscapeXmlComment(string? text)
    {
        if (string.IsNullOrEmpty(text))
        {
            return string.Empty;
        }

        // Help text scraped from a CLI can embed the generating user's home directory
        // in option defaults (e.g. "/home/runner/.config/helm/..."). Those paths are
        // meaningless to consumers, so normalize them to "~" before shipping docs.
        text = RunnerHomePathPattern().Replace(text, "~");
        text = text
            .Replace("\r\n", " ")
            .Replace("\n", " ")
            .Replace("\r", " ");
        text = string.Concat(text.Select(static character => char.IsControl(character) ? ' ' : character));

        return text
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;")
            .Trim();
    }

