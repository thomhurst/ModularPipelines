    /// </summary>
    /// <param name="propertyName">The C# property name of the option.</param>
    /// <param name="isFlag">Whether this is a boolean flag (flags are not considered secrets).</param>
    /// <param name="description">The option description, when available.</param>
    /// <returns>True if the option should be marked as a secret.</returns>
    public static bool IsSecretOption(string propertyName, bool isFlag, string? description = null)
    {
        if (string.IsNullOrEmpty(propertyName))
        {
            return false;
        }

        // A secrets provider identifies the encryption backend (for example "default"
        // or "passphrase"); it is not itself secret material.
        if (propertyName.EndsWith("SecretsProvider", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        var hasSecretKeyword = SecretKeywords.Any(keyword =>
                                   propertyName.Contains(keyword, StringComparison.OrdinalIgnoreCase))
                               || ContainsIdentifierSegment(propertyName, "Otp");
        if (!hasSecretKeyword || IsFilePathOption(propertyName, description))
        {
            return false;
        }

        // A keyword-bearing flag is suspicious, but has no value to mask. The
        // enhancer reports it so a bad scraped type cannot pass unnoticed.
        return !isFlag;
    }

    internal static bool IsFilePathOption(string propertyName, string? description)
    {
        return FilePathPropertySuffixes.Any(suffix =>
                   propertyName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
               || description?.Contains("path to", StringComparison.OrdinalIgnoreCase) == true;
    }

    private static bool ContainsIdentifierSegment(string propertyName, string segment)
    {
        for (var index = propertyName.IndexOf(segment, StringComparison.OrdinalIgnoreCase);
             index >= 0;
             index = propertyName.IndexOf(segment, index + 1, StringComparison.OrdinalIgnoreCase))
        {
            var startsAtBoundary = index == 0
                                   || (char.IsUpper(propertyName[index])
                                       && (char.IsLower(propertyName[index - 1])
                                           || char.IsDigit(propertyName[index - 1])
                                           || propertyName[index - 1] == '_'));
            var endIndex = index + segment.Length;
            var endsAtBoundary = endIndex == propertyName.Length
                                 || char.IsUpper(propertyName[endIndex])
                                 || char.IsDigit(propertyName[endIndex])
                                 || propertyName[endIndex] == '_';
            if (startsAtBoundary && endsAtBoundary)
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Throws if two generated files resolve to the same output path (case-insensitive).
    /// Without this check, generators that compute colliding paths silently overwrite each
    /// other (last writer wins), which is how single-command tools ended up shipping an
    /// abstract options class where a concrete command options class was expected. Paths
    /// differing only by case are also rejected because they collide on case-insensitive
    /// filesystems.
    /// </summary>
    /// <param name="files">The files produced for the current tool.</param>
    /// <param name="previouslyEmittedPaths">
    /// Normalized (forward-slash) paths already emitted earlier in the run, so tools
    /// sharing an output directory can't overwrite each other's files either.
    /// </param>
    public static void EnsureNoDuplicateFilePaths(
        IEnumerable<GeneratedFile> files,
        IReadOnlySet<string>? previouslyEmittedPaths = null)
    {
        ArgumentNullException.ThrowIfNull(files);

        var normalizedPaths = files
            .Select(f => f.RelativePath.Replace('\\', '/'))
            .ToList();

        var duplicates = normalizedPaths
            .GroupBy(p => p, StringComparer.OrdinalIgnoreCase)
            .Where(g => g.Count() > 1)
            .Select(g => g.Key)
            .Concat(previouslyEmittedPaths is null
                ? []
                : normalizedPaths.Where(previouslyEmittedPaths.Contains))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();

        if (duplicates.Count > 0)
        {
            throw new InvalidOperationException(
                $"Multiple generators produced the same output path(s): {string.Join(", ", duplicates)}. " +
                "Each generated file must have a unique, case-insensitively distinct path.");
        }
    }

    /// <summary>
    /// Renames command options classes that share their name with the parent global-options
    /// class. The allocated fallback is guaranteed not to collide with another command class.
    /// </summary>
    public static IReadOnlyList<CliCommandDefinition> NormalizeCommandClassNames(IReadOnlyList<CliCommandDefinition> commands)
    {
        ArgumentNullException.ThrowIfNull(commands);

        if (!commands.Any(command => NeedsClassNameNormalization(command)))
        {
            return commands;
        }

        var occupiedClassNames = commands
            .Select(command => command.ClassName)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        var normalizedCommands = new List<CliCommandDefinition>(commands.Count);

        foreach (var command in commands)
        {
            if (!NeedsClassNameNormalization(command))
            {
                normalizedCommands.Add(command);
                continue;
            }

            var className = AllocateExecuteClassName(command, occupiedClassNames);
            normalizedCommands.Add(command with { ClassName = className });
        }

        return normalizedCommands;
    }

    /// <summary>
    /// Returns the root-level commands (no sub-domain) whose generated method name does not
    /// collide with a sub-domain property name. Shared by ServiceInterfaceGenerator and
    /// ServiceImplementationGenerator so the interface and implementation can never disagree
    /// about which methods exist. Colliding single-part commands are not lost: the
    /// SubDomainClassGenerator surfaces them as ExecuteAsync() on the sub-domain class.
    /// </summary>
    public static IReadOnlyList<CliCommandDefinition> GetNonCollidingRootCommands(CliToolDefinition tool)
    {
        ArgumentNullException.ThrowIfNull(tool);

        var subDomainNames = GetSubDomainIdentifiers(tool);

        var rootCommands = tool.Commands
            .Where(c => c.SubDomainGroup is null)
            .Where(c => !subDomainNames.Contains(GetCommandGroupIdentifier(c)))
            .ToList();

        // Distinct commands can normalize to the same method name (e.g. "build-server"
        // and "build_server" both become BuildServer). Emitting both would produce
        // duplicate members the duplicate-path check cannot see, so fail loudly here.
        var duplicateMethodNames = GetDuplicateCommandGroups(
                rootCommands,
                command => GenerateMethodNameFromCommandParts(command.CommandParts))
            .Select(g => $"{g.Key} ({string.Join(", ", g.Select(c => c.FullCommand))})")
            .ToList();

        if (duplicateMethodNames.Count > 0)
        {
            throw new InvalidOperationException(
                $"Multiple {tool.ToolName} commands normalize to the same method name: " +
                $"{string.Join("; ", duplicateMethodNames)}. Rename or exclude one in the scraper.");
        }

        return rootCommands;
    }

    /// <summary>
    /// Returns executable root commands that own a generated sub-domain. These commands
    /// are exposed as <c>Execute</c> on the matching sub-domain class.
    /// </summary>
    internal static IReadOnlyList<CliCommandDefinition> GetSubDomainParentCommands(CliToolDefinition tool)
    {
        ArgumentNullException.ThrowIfNull(tool);

        var subDomainNames = GetSubDomainIdentifiers(tool);
        var parentCommands = tool.Commands
            .Where(command => command.SubDomainGroup is null)
            .Where(command => command.CommandParts.Length == 1)
            .Where(command => subDomainNames.Contains(GetCommandGroupIdentifier(command)))
            .ToList();

        var duplicateParentGroups = GetDuplicateCommandGroups(
                parentCommands,
                GetCommandGroupIdentifier)
            .Select(group =>
                $"{group.Key} ({string.Join(", ", group.Select(command => command.FullCommand))})")
            .ToList();

        if (duplicateParentGroups.Count > 0)
        {
            throw new InvalidOperationException(
                $"The {tool.ToolName} scraper produced multiple definitions for the same root command(s): " +
                $"{string.Join("; ", duplicateParentGroups)}. Fix the scraper to emit each command once.");
        }

        return parentCommands;
    }

    /// <summary>
    /// Gets the generated identifier for a sub-domain while preserving legacy casing unless
    /// the scraper supplied an explicit tool-specific override.
    /// </summary>
    public static string GetSubDomainIdentifier(CliToolDefinition tool, string subDomainGroup)
    {
        ArgumentNullException.ThrowIfNull(tool);
        ArgumentException.ThrowIfNullOrWhiteSpace(subDomainGroup);

        var overrides = tool.Commands
            .Where(command => string.Equals(
                command.SubDomainGroup,
                subDomainGroup,
                StringComparison.OrdinalIgnoreCase))
            .Select(command => command.CommandGroupIdentifierOverride)
            .Where(identifier => identifier is not null)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();

        return overrides.Count switch
        {
            0 => ToPascalCase(subDomainGroup),
            1 => overrides[0]!,
            _ => throw new InvalidOperationException(
                $"The {tool.ToolName} scraper produced conflicting identifiers for sub-domain " +
                $"'{subDomainGroup}': {string.Join(", ", overrides)}.")
        };
    }

    internal static IReadOnlyList<CliCommandGroupAlias> GetCommandGroupAliases(
        CliToolDefinition tool,
        string canonicalIdentifier)
    {
        ArgumentNullException.ThrowIfNull(tool);
        ArgumentException.ThrowIfNullOrWhiteSpace(canonicalIdentifier);

        return tool.CommandGroupAliases
            .Where(alias => GetCanonicalCommandGroupIdentifier(tool, alias)
                .Equals(canonicalIdentifier, StringComparison.OrdinalIgnoreCase))
            .OrderBy(alias => alias.Alias, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    internal static string GetAliasCommandGroupIdentifier(CliCommandGroupAlias alias)
    {
        ArgumentNullException.ThrowIfNull(alias);
        return ToPascalCase(alias.Alias);
    }

    internal static string GetCanonicalCommandGroupIdentifier(
        CliToolDefinition tool,
        CliCommandGroupAlias alias)
    {
        ArgumentNullException.ThrowIfNull(tool);
        ArgumentNullException.ThrowIfNull(alias);

        var identifiers = tool.Commands
            .Where(command => command.CommandParts.Length > 0
                && command.CommandParts[0].Equals(
                    alias.CanonicalCommand,
                    StringComparison.OrdinalIgnoreCase))
            .Select(command => command.CommandGroupIdentifierOverride
                ?? ToPascalCase(command.CommandParts[0]))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();

        return identifiers.Count switch
        {
            1 => identifiers[0],
            0 => throw new InvalidOperationException(
                $"Command-group alias '{alias.Alias}' targets missing canonical command "
                + $"'{alias.CanonicalCommand}' for {tool.ToolName}."),
            _ => throw new InvalidOperationException(
                $"Command-group alias '{alias.Alias}' targets canonical command "
                + $"'{alias.CanonicalCommand}' with conflicting generated identifiers: "
                + string.Join(", ", identifiers)),
        };
    }

    internal static string GetAliasedClassName(
        CliToolDefinition tool,
        CliCommandGroupAlias alias,
        string canonicalClassName)
    {
        var canonicalPrefix =
            $"{tool.NamespacePrefix}{GetCanonicalCommandGroupIdentifier(tool, alias)}";
        if (!canonicalClassName.StartsWith(canonicalPrefix, StringComparison.Ordinal))
        {
            throw new InvalidOperationException(
                $"Canonical class '{canonicalClassName}' does not start with expected "
                + $"command-group prefix '{canonicalPrefix}'.");
        }

        return $"{tool.NamespacePrefix}{GetAliasCommandGroupIdentifier(alias)}"
            + canonicalClassName[canonicalPrefix.Length..];
    }

    internal static string GetCommandGroupIdentifier(CliCommandDefinition command) =>
        command.CommandGroupIdentifierOverride
        ?? GenerateMethodNameFromCommandParts(command.CommandParts);

    private static HashSet<string> GetSubDomainIdentifiers(CliToolDefinition tool) =>
        new(
            tool.SubDomainGroups.Select(group => GetSubDomainIdentifier(tool, group)),
            StringComparer.OrdinalIgnoreCase);

    private static IEnumerable<IGrouping<string, CliCommandDefinition>> GetDuplicateCommandGroups(
        IEnumerable<CliCommandDefinition> commands,
        Func<CliCommandDefinition, string> identifierSelector) =>
        commands
            .GroupBy(identifierSelector, StringComparer.OrdinalIgnoreCase)
            .Where(group => group.Skip(1).Any());

    private static bool NeedsClassNameNormalization(CliCommandDefinition command) =>
        string.Equals(command.ClassName, command.ParentClassName, StringComparison.OrdinalIgnoreCase);

    private static string AllocateExecuteClassName(
        CliCommandDefinition command,
        ISet<string> occupiedClassNames)
    {
        var baseName = command.ParentClassName.EndsWith("Options", StringComparison.Ordinal)
            ? command.ParentClassName[..^"Options".Length]
            : command.ParentClassName;
        var suffix = "Execute";
        var candidate = $"{baseName}{suffix}Options";

        while (!occupiedClassNames.Add(candidate))
        {
            suffix += "Execute";
            candidate = $"{baseName}{suffix}Options";
        }

        return candidate;
    }
