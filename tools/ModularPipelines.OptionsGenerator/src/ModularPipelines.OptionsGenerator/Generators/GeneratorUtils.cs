    private static string GenerateCliFlagAttributeString(CliOptionDefinition option)
    {
        var parts = new List<string> { FormatStringLiteral(option.SwitchName) };

        if (!string.IsNullOrEmpty(option.ShortForm))
        {
            parts.Add($"ShortForm = {FormatStringLiteral(option.ShortForm)}");
        }

        if (option.PreferShortForm)
        {
            parts.Add("PreferShortForm = true");
        }

        if (option.Phase != CommandLinePhase.Normal)
        {
            parts.Add($"Phase = CommandLinePhase.{option.Phase}");
        }

        return $"CliFlag({string.Join(", ", parts)})";
    }

    private static string GenerateCliOptionAttributeString(CliOptionDefinition option)
    {
        var optionParts = new List<string> { FormatStringLiteral(option.SwitchName) };

        if (!string.IsNullOrEmpty(option.ShortForm))
        {
            optionParts.Add($"ShortForm = {FormatStringLiteral(option.ShortForm)}");
        }

        if (option.PreferShortForm)
        {
            optionParts.Add("PreferShortForm = true");
        }

        if (option.ValueSeparator == "=")
        {
            optionParts.Add("Format = OptionFormat.EqualsSeparated");
        }
        else if (option.ValueSeparator == ":")
        {
            optionParts.Add("Format = OptionFormat.ColonSeparated");
        }
        else if (option.ValueSeparator == string.Empty)
        {
            optionParts.Add("Format = OptionFormat.NoSeparator");
        }
        else if (option.ValueSeparator != " " && !string.IsNullOrEmpty(option.ValueSeparator))
        {
            optionParts.Add($"CustomSeparator = {FormatStringLiteral(option.ValueSeparator)}");
        }

        if (option.AcceptsMultipleValues)
        {
            optionParts.Add("AllowMultiple = true");
        }

        if (option.ValueArity != CliOptionValueArity.Required)
        {
            optionParts.Add($"ValueArity = CliOptionValueArity.{option.ValueArity}");
        }

        if (option.Phase != CommandLinePhase.Normal)
        {
            optionParts.Add($"Phase = CommandLinePhase.{option.Phase}");
        }

        return $"CliOption({string.Join(", ", optionParts)})";
    }

    /// <summary>
    /// Generates validation attribute lines for an option with validation constraints.
    /// </summary>
    /// <param name="sb">The StringBuilder to append to.</param>
    /// <param name="constraints">The validation constraints.</param>
    /// <param name="indent">The indentation string (defaults to 4 spaces).</param>
    public static void GenerateValidationAttributes(StringBuilder sb, CliValidationConstraints constraints, string indent = "    ")
    {
        ArgumentNullException.ThrowIfNull(sb);
        ArgumentNullException.ThrowIfNull(constraints);

        if (constraints.MinValue.HasValue || constraints.MaxValue.HasValue)
        {
            var min = constraints.MinValue ?? int.MinValue;
            var max = constraints.MaxValue ?? int.MaxValue;
            sb.AppendLine($"{indent}[Range({min}, {max})]");
        }

        if (!string.IsNullOrEmpty(constraints.Pattern))
        {
            sb.AppendLine(
                $"{indent}[RegularExpression({FormatStringLiteral(constraints.Pattern)})]");
        }
    }

