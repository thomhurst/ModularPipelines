    /// <summary>
    /// Converts a CLI option name to a valid C# enum name.
    /// Example: "--verbosity" -> "Verbosity", "--dry-run" -> "DryRun"
    /// </summary>
    public static string ToEnumName(string optionName, string commandPrefix)
    {
        var cleaned = optionName.TrimStart('-');
        var pascalCase = ToPascalCase(cleaned);
        return $"{commandPrefix}{pascalCase}";
    }

    /// <summary>
    /// Converts a CLI enum value to a valid C# enum member name.
    /// Example: "quiet" -> "Quiet", "dry-run" -> "DryRun", "1" -> "Value1"
    /// </summary>
    public static string ToEnumMemberName(string cliValue)
    {
        if (string.IsNullOrWhiteSpace(cliValue))
        {
            return "Unknown";
        }

        var normalizedValue = InvalidIdentifierCharacterPattern().Replace(cliValue, " ");
        var pascalCase = ToPascalCasePreservingWordBoundaries(normalizedValue);
        if (string.IsNullOrEmpty(pascalCase))
        {
            return "Unknown";
        }

        // Ensure it starts with a letter
        if (!char.IsLetter(pascalCase[0]))
        {
            pascalCase = $"Value{pascalCase.TrimStart('_')}";
        }

        return pascalCase;
    }

    /// <summary>
    /// Converts a string to PascalCase.
    /// Handles kebab-case, snake_case, and space-separated words.
    /// Ensures the result is a valid C# identifier (starts with a letter).
    /// </summary>
    public static string ToPascalCase(string input)
    {
        if (string.IsNullOrWhiteSpace(input))
        {
            return string.Empty;
        }

        // Split on common separators
        var words = SeparatorPattern().Split(input);
        var sb = new StringBuilder();

        foreach (var word in words)
        {
            if (string.IsNullOrWhiteSpace(word))
            {
                continue;
            }

            if (CompoundWordCasing.TryGetValue(word, out var compoundWord))
            {
                sb.Append(compoundWord);
                continue;
            }

            if (!word.Any(char.IsUpper))
            {
                sb.Append(char.ToUpperInvariant(word[0]));
                if (word.Length > 1)
                {
                    sb.Append(word[1..].ToLowerInvariant());
                }

                continue;
            }

            var identifierWords = IdentifierWordPattern().Matches(word);
            foreach (Match identifierWord in identifierWords)
            {
                sb.Append(char.ToUpperInvariant(identifierWord.Value[0]));
                if (identifierWord.Length > 1)
                {
                    sb.Append(identifierWord.Value[1..].ToLowerInvariant());
                }
            }
        }

        var result = sb.ToString();

        // Ensure the result is a valid C# identifier (must start with a letter or underscore)
        // Handles cases like "9p" (filesystem protocol) -> "_9p"
        if (result.Length > 0 && !char.IsLetter(result[0]))
        {
            result = "_" + result;
        }

        return result;
    }

    private static string ToPascalCasePreservingWordBoundaries(string input)
    {
        var words = SeparatorPattern()
            .Split(input)
            .SelectMany(word => IdentifierWordPattern().Matches(word).Select(match => match.Value));
        var sb = new StringBuilder();

        foreach (var word in words)
        {
            sb.Append(char.ToUpperInvariant(word[0]));
            if (word.Length > 1)
            {
                sb.Append(word[1..].ToLowerInvariant());
            }
        }

        return sb.ToString();
    }

