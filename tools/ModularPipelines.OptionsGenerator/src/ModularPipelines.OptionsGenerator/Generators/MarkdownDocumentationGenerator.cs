using System.Text;
using System.Text.RegularExpressions;
using ModularPipelines.OptionsGenerator.Models;

namespace ModularPipelines.OptionsGenerator.Generators;

/// <summary>
/// Generates a Docusaurus command-reference page from the same metadata as the CLI API.
/// </summary>
public partial class MarkdownDocumentationGenerator : ICodeGenerator, IGeneratedFileCleanupProvider
{
    private const string GeneratedMarker = "<!-- This file is generated by ModularPipelines.OptionsGenerator. -->";
    private static readonly string DocumentationDirectory = Path.Combine("docs", "docs", "mp-packages", "cli");

    public Task<IReadOnlyList<GeneratedFile>> GenerateAsync(
        CliToolDefinition tool,
        CancellationToken cancellationToken = default)
    {
        var documentationOutputDirectory = tool.DocumentationOutputDirectory;
        if (string.IsNullOrWhiteSpace(documentationOutputDirectory))
        {
            return Task.FromResult<IReadOnlyList<GeneratedFile>>([]);
        }

        tool = DocumentationExampleCatalog.Apply(tool);
        tool = ExecutablePrerequisiteCatalog.Apply(tool);
        var file = new GeneratedFile
        {
            RelativePath = Path.Combine(documentationOutputDirectory, GetFileName(tool.ToolName)),
            Content = GenerateMarkdown(tool),
        };

        return Task.FromResult<IReadOnlyList<GeneratedFile>>([file]);
    }

    public IEnumerable<GeneratedFileCleanupRule> GetCleanupRules(IReadOnlyCollection<string> toolNames)
    {
        yield return new GeneratedFileCleanupRule
        {
            RelativeDirectory = DocumentationDirectory,
            SearchPattern = "*.md",
            GeneratedMarker = GeneratedMarker,
            ExpectedFileNames = toolNames.Select(GetFileName).ToHashSet(StringComparer.OrdinalIgnoreCase),
        };
    }

    private static string GenerateMarkdown(CliToolDefinition tool)
    {
        var commands = GetExposedCommands(tool);
        var sb = new StringBuilder();

        sb.AppendLine("---");
        sb.AppendLine($"title: {tool.ToolName} CLI reference");
        sb.AppendLine("---");
        sb.AppendLine(GeneratedMarker);
        sb.AppendLine();
        sb.AppendLine($"# {tool.ToolName} CLI reference");
        sb.AppendLine();
        sb.AppendLine($"`{tool.TargetNamespace}` provides strongly typed access to the `{tool.ToolName}` CLI.");
        sb.AppendLine();
        AppendExecutablePrerequisite(sb, tool);
        sb.AppendLine("## Package installation");
        sb.AppendLine();
        sb.AppendLine("```shell");
        sb.AppendLine($"dotnet add package {tool.TargetNamespace}");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine($"Resolve the service with `context.Tools.{tool.NamespacePrefix}`.");
        sb.AppendLine(
            $"Projects using C# 13 or another .NET language can use `context.Tools.Get<{tool.TargetNamespace}.Services.I{tool.NamespacePrefix}>()` instead.");
        sb.AppendLine();
        AppendExample(sb, tool, commands);
        AppendGlobalOptions(sb, tool);
        AppendCoverageExclusions(sb, tool);
        sb.AppendLine("## Commands");
        sb.AppendLine();
        sb.AppendLine("| CLI command | Options record |");
        sb.AppendLine("| --- | --- |");

        foreach (var command in commands.OrderBy(command => command.FullCommand, StringComparer.OrdinalIgnoreCase))
        {
            sb.AppendLine($"| `{EscapeTableCell(command.FullCommand)}` | `{command.ClassName}` |");
        }

        return sb.ToString();
    }

    private static void AppendGlobalOptions(StringBuilder sb, CliToolDefinition tool)
    {
        var options = tool.GetGlobalOptions();
        if (options.Count == 0)
        {
            return;
        }

        sb.AppendLine("## Global options");
        sb.AppendLine();
        sb.AppendLine("Global options are rendered before the selected subcommand.");
        sb.AppendLine();
        sb.AppendLine("| CLI option | Property | Availability | Description |");
        sb.AppendLine("| --- | --- | --- | --- |");

        foreach (var option in options.OrderBy(option => option.SwitchName, StringComparer.OrdinalIgnoreCase))
        {
            var optionName = option.DocumentationUrl is null
                ? $"`{EscapeTableCell(option.SwitchName)}`"
                : $"[`{EscapeTableCell(option.SwitchName)}`]({option.DocumentationUrl})";
            sb.AppendLine(
                $"| {optionName} | `{EscapeTableCell(option.PropertyName)}` | {EscapeTableCell(option.Availability ?? "All editions")} | {EscapeTableCell(option.Description ?? string.Empty)} |");
        }

        sb.AppendLine();
    }

    private static void AppendCoverageExclusions(StringBuilder sb, CliToolDefinition tool)
    {
        if (tool.CommandCoverage.Exclusions.Count == 0)
        {
            return;
        }

        sb.AppendLine("## Intentionally excluded commands");
        sb.AppendLine();
        sb.AppendLine("| CLI command | Reason |");
        sb.AppendLine("| --- | --- |");

        foreach (var exclusion in tool.CommandCoverage.Exclusions
                     .OrderBy(item => item.Command, StringComparer.OrdinalIgnoreCase))
        {
            sb.AppendLine(
                $"| `{EscapeTableCell(exclusion.Command)}` | {EscapeTableCell(exclusion.Reason)} |");
        }

        sb.AppendLine();
    }

    private static void AppendExecutablePrerequisite(StringBuilder sb, CliToolDefinition tool)
    {
        var prerequisite = tool.ExecutablePrerequisite;
        var commandName = prerequisite?.CommandName ?? tool.ToolName;

        sb.AppendLine("## Executable prerequisite");
        sb.AppendLine();
        sb.AppendLine(
            $"This package does not install the `{commandName}` executable. "
            + $"Install it separately and ensure `{commandName}` is available on `PATH`.");
        sb.AppendLine();

        if (!string.IsNullOrWhiteSpace(prerequisite?.SupportedVersion))
        {
            sb.AppendLine(
                $"The generation workflow is pinned to `{commandName}` version "
                + $"`{prerequisite.SupportedVersion}`.");
            sb.AppendLine();
        }

        if (!string.IsNullOrWhiteSpace(prerequisite?.InstallationUrl))
        {
            sb.AppendLine($"See the [{commandName} installation guide]({prerequisite.InstallationUrl}).");
            sb.AppendLine();
        }

        if (!string.IsNullOrWhiteSpace(prerequisite?.InstallationNotes))
        {
            sb.AppendLine(prerequisite.InstallationNotes);
            sb.AppendLine();
        }
        else if (prerequisite is null
                 && string.IsNullOrWhiteSpace(tool.ExecutablePrerequisiteMetadataExemption))
        {
            sb.AppendLine(ExecutablePrerequisiteCatalog.GenericInstallationNotes);
            sb.AppendLine();
        }

        if (!string.IsNullOrWhiteSpace(tool.ExecutablePrerequisiteMetadataExemption))
        {
            sb.AppendLine(tool.ExecutablePrerequisiteMetadataExemption);
            sb.AppendLine();
        }
    }

    private static void AppendExample(
        StringBuilder sb,
        CliToolDefinition tool,
        IReadOnlyCollection<CliCommandDefinition> commands)
    {
        sb.AppendLine("## Module example");
        sb.AppendLine();

        var command = SelectExampleCommand(tool, commands);
        if (command is null)
        {
            var onlyUnsafeCommands = commands.Count > 0
                                     && commands.All(candidate => candidate.IsInteractive || candidate.IsDestructive);
            var omissionReason = onlyUnsafeCommands
                ? "Unsafe or destructive commands do not receive runnable examples:"
                : "A runnable example is omitted when no command has complete safety metadata:";
            sb.AppendLine(
                "Resolve the service in a module, then select a command from the table below. "
                + omissionReason);
            sb.AppendLine();
            sb.AppendLine("```csharp");
            sb.AppendLine(
                $"var {ToCamelCase(tool.NamespacePrefix)} = context.Tools.{tool.NamespacePrefix};");
            sb.AppendLine("```");
            sb.AppendLine();
            return;
        }

        var invocation = BuildInvocation(tool, command);
        var optionsExpression = BuildOptionsExpression(command);

        sb.AppendLine("```csharp");
        sb.AppendLine("using ModularPipelines;");
        sb.AppendLine($"using {tool.TargetNamespace}.Options;");
        sb.AppendLine();
        sb.AppendLine("public class RunCommandModule : Module<CommandResult>");
        sb.AppendLine("{");
        sb.AppendLine("    protected override async Task<CommandResult> ExecuteAsync(");
        sb.AppendLine("        IModuleContext context,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine($"        return await {invocation}(");
        AppendIndentedExpression(sb, optionsExpression, "            ", appendComma: true);
        sb.AppendLine("            cancellationToken: cancellationToken);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine("```");
        sb.AppendLine();
    }

    private static CliCommandDefinition? SelectExampleCommand(
        CliToolDefinition tool,
        IReadOnlyCollection<CliCommandDefinition> commands)
    {
        if (string.IsNullOrWhiteSpace(tool.PreferredDocumentationExampleCommand))
        {
            return null;
        }

        var command = commands
            .FirstOrDefault(candidate => string.Equals(
                candidate.FullCommand,
                tool.PreferredDocumentationExampleCommand,
                StringComparison.OrdinalIgnoreCase));

        if (command is null)
        {
            throw new InvalidOperationException(
                $"Preferred documentation example command "
                + $"'{tool.PreferredDocumentationExampleCommand}' for '{tool.ToolName}' "
                + "does not match an emitted command.");
        }

        if (!command.IsSafeForDocumentation || command.IsInteractive || command.IsDestructive)
        {
            throw new InvalidOperationException(
                $"Preferred documentation example command '{command.FullCommand}' for "
                + $"'{tool.ToolName}' does not have complete safe-example metadata.");
        }

        return command;
    }

    internal static string BuildInvocation(
        CliToolDefinition tool,
        CliCommandDefinition command)
    {
        if (command.SubDomainGroup is null)
        {
            var rootMethod = GeneratorUtils.GenerateMethodNameFromCommandParts(command.CommandParts);
            var emittedRootCommand = GeneratorUtils.GetNonCollidingRootCommands(tool)
                .Any(candidate => string.Equals(
                    candidate.FullCommand,
                    command.FullCommand,
                    StringComparison.OrdinalIgnoreCase));
            if (!emittedRootCommand)
            {
                var subDomainParent = GeneratorUtils.GetSubDomainParentCommands(tool)
                    .FirstOrDefault(candidate => string.Equals(
                        candidate.FullCommand,
                        command.FullCommand,
                        StringComparison.OrdinalIgnoreCase));
                if (subDomainParent is null)
                {
                    throw new InvalidOperationException(
                        $"Preferred documentation example command '{command.FullCommand}' for "
                        + $"'{tool.ToolName}' is not exposed as a service method.");
                }

                var subDomain = GeneratorUtils.GetCommandGroupIdentifier(subDomainParent);
                return $"context.Tools.{tool.NamespacePrefix}.{subDomain}.ExecuteAsync";
            }

            return $"context.Tools.{tool.NamespacePrefix}.{GeneratorUtils.EnsureAsyncSuffix(rootMethod)}";
        }

        var navigationSegments = new List<string>
        {
            GeneratorUtils.GetSubDomainIdentifier(tool, command.SubDomainGroup),
        };
        navigationSegments.AddRange(command.CommandParts
            .Skip(1)
            .SkipLast(1)
            .Select(GeneratorUtils.ToPascalCase));

        if (tool.Commands.Any(candidate =>
                string.Equals(
                    candidate.SubDomainGroup,
                    command.SubDomainGroup,
                    StringComparison.OrdinalIgnoreCase)
                && IsCommandPrefix(command, candidate)))
        {
            navigationSegments.Add(GeneratorUtils.ToPascalCase(command.CommandParts[^1]));
            return $"context.Tools.{tool.NamespacePrefix}.{string.Join('.', navigationSegments)}.ExecuteAsync";
        }

        var methodName = GeneratorUtils.GenerateSubDomainMethodName(
            command,
            HasExecutableParentCommand(tool, command),
            GetSiblingCommands(tool, command));
        return $"context.Tools.{tool.NamespacePrefix}.{string.Join('.', navigationSegments)}.{GeneratorUtils.EnsureAsyncSuffix(methodName)}";
    }

    private static IReadOnlyList<CliCommandDefinition> GetSiblingCommands(
        CliToolDefinition tool,
        CliCommandDefinition command)
    {
        var subDomainCommands = tool.Commands
            .Where(candidate => string.Equals(
                candidate.SubDomainGroup,
                command.SubDomainGroup,
                StringComparison.OrdinalIgnoreCase))
            .ToList();
        var node = CommandTreeNode.BuildTree(
            tool.NamespacePrefix,
            GeneratorUtils.GetSubDomainIdentifier(tool, command.SubDomainGroup!),
            subDomainCommands);

        for (var partIndex = 1; partIndex < command.CommandParts.Length - 1; partIndex++)
        {
            if (!node.Children.TryGetValue(command.CommandParts[partIndex], out node))
            {
                return [];
            }
        }

        return node.GetNamedFacadeCommands();
    }

    private static bool HasExecutableParentCommand(
        CliToolDefinition tool,
        CliCommandDefinition command)
    {
        if (command.CommandParts.Length < 2)
        {
            return false;
        }

        if (command.CommandParts.Length == 2)
        {
            var subDomainIdentifier = GeneratorUtils.GetSubDomainIdentifier(
                tool,
                command.SubDomainGroup!);
            return GeneratorUtils.GetSubDomainParentCommands(tool)
                .Any(candidate => string.Equals(
                    GeneratorUtils.GetCommandGroupIdentifier(candidate),
                    subDomainIdentifier,
                    StringComparison.OrdinalIgnoreCase));
        }

        var parentPathLength = command.CommandParts.Length - 2;
        var nodeIdentifier = GeneratorUtils.ToPascalCase(command.CommandParts[^2]);
        return tool.Commands.Any(candidate =>
            string.Equals(
                candidate.SubDomainGroup,
                command.SubDomainGroup,
                StringComparison.OrdinalIgnoreCase)
            && candidate.CommandParts.Length == command.CommandParts.Length - 1
            && candidate.CommandParts
                .Take(parentPathLength)
                .SequenceEqual(
                    command.CommandParts.Take(parentPathLength),
                    StringComparer.OrdinalIgnoreCase)
            && string.Equals(
                GeneratorUtils.GenerateMethodNameFromLastCommandPart(candidate),
                nodeIdentifier,
                StringComparison.OrdinalIgnoreCase));
    }

    private static bool IsCommandPrefix(
        CliCommandDefinition command,
        CliCommandDefinition candidate) =>
        candidate.CommandParts.Length > command.CommandParts.Length
        && command.CommandParts.SequenceEqual(
            candidate.CommandParts.Take(command.CommandParts.Length),
            StringComparer.OrdinalIgnoreCase);

    private static string BuildOptionsExpression(CliCommandDefinition command)
    {
        var values = command.DocumentationExampleValues;
        var requiredParameters = GeneratorUtils.GetRequiredConstructorParameters(command);
        var positionalArguments = CliPositionalArgument.MergeDuplicates(command.PositionalArguments);
        var knownProperties = command.Options
            .Select(option => option.PropertyName)
            .Concat(positionalArguments.Select(argument => argument.PropertyName))
            .Distinct(StringComparer.Ordinal)
            .ToArray();

        foreach (var value in values)
        {
            if (string.IsNullOrWhiteSpace(value.Value))
            {
                throw InvalidExample(command, $"sample value for '{value.Key}' is empty");
            }

            if (!knownProperties.Contains(value.Key, StringComparer.Ordinal))
            {
                throw InvalidExample(command, $"sample property '{value.Key}' is not generated");
            }
        }

        foreach (var parameter in requiredParameters)
        {
            if (!values.ContainsKey(parameter.PropertyName))
            {
                throw InvalidExample(command, $"required property '{parameter.PropertyName}' has no sample value");
            }
        }

        var constructorValues = requiredParameters
            .Select(parameter => values[parameter.PropertyName])
            .ToArray();
        var expression = new StringBuilder()
            .Append("new ")
            .Append(command.ClassName)
            .Append('(')
            .AppendJoin(", ", constructorValues)
            .Append(')');
        var requiredPropertyNames = requiredParameters
            .Select(parameter => parameter.PropertyName)
            .ToHashSet(StringComparer.Ordinal);
        var initializedProperties = knownProperties
            .Where(values.ContainsKey)
            .Where(property => !requiredPropertyNames.Contains(property))
            .ToArray();

        if (initializedProperties.Length == 0)
        {
            return expression.ToString();
        }

        expression.AppendLine()
            .AppendLine("{");
        foreach (var property in initializedProperties)
        {
            expression.Append("    ")
                .Append(property)
                .Append(" = ")
                .Append(values[property])
                .AppendLine(",");
        }

        return expression.Append('}').ToString();
    }

    private static InvalidOperationException InvalidExample(
        CliCommandDefinition command,
        string reason) =>
        new($"Documentation example metadata for '{command.FullCommand}' is invalid: {reason}.");

    private static void AppendIndentedExpression(
        StringBuilder sb,
        string expression,
        string indentation,
        bool appendComma)
    {
        var lines = expression.ReplaceLineEndings("\n").Split('\n');
        for (var index = 0; index < lines.Length; index++)
        {
            sb.Append(indentation).Append(lines[index]);
            if (appendComma && index == lines.Length - 1)
            {
                sb.Append(',');
            }

            sb.AppendLine();
        }
    }

    private static IReadOnlyList<CliCommandDefinition> GetExposedCommands(CliToolDefinition tool)
    {
        var exposedRootCommands = GeneratorUtils.GetNonCollidingRootCommands(tool)
            .Concat(GeneratorUtils.GetSubDomainParentCommands(tool))
            .Select(command => command.ClassName)
            .ToHashSet(StringComparer.Ordinal);

        return tool.Commands
            .Where(command =>
                (command.SubDomainGroup is not null ||
                 exposedRootCommands.Contains(command.ClassName)))
            .DistinctBy(command => command.ClassName)
            .ToList();
    }

    private static string EscapeTableCell(string value) => value.Replace("|", "\\|", StringComparison.Ordinal);

    private static string ToCamelCase(string value) => char.ToLowerInvariant(value[0]) + value[1..];

    private static string GetFileName(string toolName) => $"{Slugify(toolName)}.md";

    private static string Slugify(string value) =>
        RepeatedHyphenRegex().Replace(NonSlugCharacterRegex().Replace(value.ToLowerInvariant(), "-"), "-").Trim('-');

    [GeneratedRegex("[^a-z0-9-]+")]
    private static partial Regex NonSlugCharacterRegex();

    [GeneratedRegex("-+")]
    private static partial Regex RepeatedHyphenRegex();
}
