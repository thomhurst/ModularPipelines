[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path
$generatedFiles = git -C $repositoryRoot ls-files -- 'src/**/*.Generated.cs'
$pattern = '\[property: CliArgument\((?<arguments>[^\r\n]*)\)\]'
$changedFiles = 0
$autoGeneratedMarker = '// <auto-generated>'

foreach ($relativePath in $generatedFiles) {
    $path = Join-Path $repositoryRoot $relativePath
    $content = [System.IO.File]::ReadAllText($path)
    $updated = [regex]::Replace(
        $content,
        $pattern,
        {
            param($match)

            $arguments = $match.Groups['arguments'].Value
            if ($arguments -match '(^|,\s*)Required\s*=') {
                return $match.Value
            }

            return "[property: CliArgument($arguments, Required = true)]"
        })

    if ($updated -ceq $content) {
        continue
    }

    if (-not $content.StartsWith($autoGeneratedMarker, [System.StringComparison]::Ordinal)) {
        throw "Refusing to migrate an unowned file: $path"
    }

    [System.IO.File]::WriteAllText($path, $updated)
    $changedFiles++
}

$helmInstallPath = Join-Path $repositoryRoot 'src/ModularPipelines.Helm/Options/HelmInstallOptions.Generated.cs'
$helmInstall = [System.IO.File]::ReadAllText($helmInstallPath)
if (-not $helmInstall.StartsWith($autoGeneratedMarker, [System.StringComparison]::Ordinal)) {
    throw "Refusing to migrate an unowned file: $helmInstallPath"
}

$originalHelmInstall = $helmInstall
$newline = if ($helmInstall.Contains("`r`n")) { "`r`n" } else { "`n" }
$recordDeclaration = "public record HelmInstallOptions : HelmOptions${newline}{"
$requiredRecordDeclaration = @(
    'public record HelmInstallOptions('
    '    [property: CliArgument(1, Phase = CommandLinePhase.EarlyOperand, Required = true)] string Chart'
    ') : HelmOptions'
    '{'
) -join $newline
$chartProperty = @(
    '    /// <summary>'
    '    /// The CHART operand.'
    '    /// </summary>'
    '    [CliArgument(1, Phase = CommandLinePhase.EarlyOperand)]'
    '    public string? Chart { get; set; }'
    ''
) -join $newline

if ($helmInstall.Contains($recordDeclaration) -and $helmInstall.Contains($chartProperty)) {
    $helmInstall = $helmInstall.Replace($recordDeclaration, $requiredRecordDeclaration)
    $helmInstall = $helmInstall.Replace($chartProperty, '')
}

$namePropertyEnd = "    public string? Name { get; set; }${newline}${newline}${newline}}"
$helmInstall = $helmInstall.Replace(
    $namePropertyEnd,
    "    public string? Name { get; set; }${newline}${newline}}")

if ($helmInstall -cne $originalHelmInstall) {
    [System.IO.File]::WriteAllText($helmInstallPath, $helmInstall)
    $changedFiles++
}

$helmServicePaths = @(
    'src/ModularPipelines.Helm/Services/Helm.Generated.cs'
    'src/ModularPipelines.Helm/Services/IHelm.Generated.cs'
)

foreach ($relativePath in $helmServicePaths) {
    $path = Join-Path $repositoryRoot $relativePath
    $content = [System.IO.File]::ReadAllText($path)
    if (-not $content.StartsWith($autoGeneratedMarker, [System.StringComparison]::Ordinal)) {
        throw "Refusing to migrate an unowned file: $path"
    }

    $updated = $content.Replace(
        'HelmInstallOptions? options = null',
        'HelmInstallOptions options')
    $updated = $updated.Replace('options ?? new HelmInstallOptions()', 'options')

    if ($updated -ceq $content) {
        continue
    }

    [System.IO.File]::WriteAllText($path, $updated)
    $changedFiles++
}

Write-Output "Updated $changedFiles generated file(s)."
