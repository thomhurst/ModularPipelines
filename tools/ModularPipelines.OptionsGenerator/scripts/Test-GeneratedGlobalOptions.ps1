$ErrorActionPreference = 'Stop'

$repositoryRoot = (& git rev-parse --show-toplevel).Trim()
if ($LASTEXITCODE -ne 0 -or -not $repositoryRoot) {
    throw 'Could not resolve the repository root.'
}

$generatedFiles = @(
    & git -C $repositoryRoot ls-files -- 'src/*/Options/*Options.Generated.cs'
)
if ($LASTEXITCODE -ne 0) {
    throw 'Could not list generated options files.'
}

$baseRecordPattern = [regex]::new(
    '(?m)^public abstract record \w+Options : CommandLineToolOptions\r?$')
$generatedBaseFiles = foreach ($relativePath in $generatedFiles) {
    $path = Join-Path $repositoryRoot $relativePath
    $content = [IO.File]::ReadAllText($path)

    if ($content.Contains('// This file was generated by ModularPipelines.OptionsGenerator.') -and
        $baseRecordPattern.IsMatch($content)) {
        [pscustomobject]@{
            RelativePath = $relativePath
            Content = $content
        }
    }
}

if ($generatedBaseFiles.Count -eq 0) {
    throw 'No generated tool base option files were found.'
}

$missing = @(
    $generatedBaseFiles | Where-Object { -not $_.Content.Contains('[CliGlobalOptions]') }
)

if ($missing.Count -eq 0) {
    Write-Host "Verified $($generatedBaseFiles.Count) generated tool bases use [CliGlobalOptions]."
    return
}

$examples = $missing |
    Select-Object -First 10 -ExpandProperty RelativePath
throw "Found $($missing.Count) generated tool bases without [CliGlobalOptions]. " +
    "Regenerate the affected tools with ModularPipelines.OptionsGenerator. " +
    "Examples: $($examples -join ', ')"
