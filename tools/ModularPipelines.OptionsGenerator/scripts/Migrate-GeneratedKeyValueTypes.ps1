[CmdletBinding()]
param(
    [string] $RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path
)

$ErrorActionPreference = 'Stop'
$sourceRoot = Join-Path $RepositoryRoot 'src'
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
$changed = 0

foreach ($file in Get-ChildItem -LiteralPath $sourceRoot -Recurse -Filter '*.Generated.cs' -File) {
    $content = [System.IO.File]::ReadAllText($file.FullName)
    $migrated = $content.Replace('KeyValue[]?', 'IReadOnlyList<KeyValue>?')
    $migrated = $migrated.Replace('IEnumerable<KeyValue>?', 'IReadOnlyList<KeyValue>?')
    $migrated = $migrated.Replace('IEnumerable<CliOptionValuePair>?', 'IEnumerable<CliValuePair>?')

    if ($migrated -eq $content) {
        continue
    }

    if (-not $content.StartsWith('// <auto-generated>', [System.StringComparison]::Ordinal)) {
        throw "Refusing to migrate an unowned file: $($file.FullName)"
    }

    [System.IO.File]::WriteAllText($file.FullName, $migrated, $utf8NoBom)
    $changed++
}

Write-Output "Migrated $changed generated option file(s)."
