[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path,
    [Parameter(Mandatory)][ValidateNotNullOrEmpty()][string]$Tool,
    [Parameter(Mandatory)][string]$PackageDirectory,
    [Parameter(Mandatory)][string]$NamespacePrefix,
    [string]$ChangeManifest
)

$ErrorActionPreference = 'Stop'
$root = [IO.Path]::TrimEndingDirectorySeparator([IO.Path]::GetFullPath($RepositoryRoot))
$package = [IO.Path]::GetFullPath((Join-Path $root $PackageDirectory))
$pathComparison = if ($IsWindows) { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }
$rootPrefix = $root.TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
if ([IO.Path]::IsPathRooted($PackageDirectory) -or -not $package.StartsWith($rootPrefix, $pathComparison) -or
    $NamespacePrefix -notmatch '^[A-Za-z][A-Za-z0-9]*$') {
    throw 'Package directory must be inside the repository and the namespace prefix must be an identifier.'
}

$optionsDirectory = Join-Path $package 'Options'
$coveragePath = Join-Path $package "Generated/$NamespacePrefix.CommandCoverage.json"
foreach ($path in @($optionsDirectory, (Split-Path $coveragePath -Parent), $coveragePath)) {
    if ((Get-Item -LiteralPath $path).Attributes -band [IO.FileAttributes]::ReparsePoint) {
        throw "Refusing to prune through a linked path: $path."
    }
}
$ancestor = $package
while (-not $ancestor.Equals($root, $pathComparison)) {
    if ((Get-Item -LiteralPath $ancestor).Attributes -band [IO.FileAttributes]::ReparsePoint) {
        throw "Refusing to prune through a linked package ancestor: $ancestor."
    }
    $ancestor = Split-Path $ancestor -Parent
}
$coverage = Get-Content -LiteralPath $coveragePath -Raw | ConvertFrom-Json
if (-not [string]::Equals($coverage.toolName, $Tool, [StringComparison]::Ordinal)) {
    throw "Command coverage tool '$($coverage.toolName)' does not match the expected package tool '$Tool'."
}
$commands = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
foreach ($command in $coverage.commands) {
    if ([string]::IsNullOrWhiteSpace($coverage.toolName) -or -not $command.StartsWith("$($coverage.toolName) ", [StringComparison]::Ordinal) -or
        -not $commands.Add($command)) {
        throw 'Command coverage must contain unique, tool-qualified commands.'
    }
}
if ($coverage.formatVersion -ne 1 -or $commands.Count -eq 0 -or $commands.Count -ne $coverage.commandCount) {
    throw 'A complete, nonempty command coverage manifest is required before pruning.'
}

# Only legacy, explicitly generated option records are eligible. Handwritten options and
# base classes remain owned by their maintainers, regardless of the coverage list.
$candidates = @(Get-ChildItem -LiteralPath $optionsDirectory -Filter '*.cs' -File | ForEach-Object {
    if ($_.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Linked options file: $($_.FullName)." }
    $content = Get-Content -LiteralPath $_.FullName -Raw
    if ($content -notmatch '(?m)^// <auto-generated>\r?$') { return }
    $attributes = [regex]::Matches($content, '(?m)^\s*\[CliSubCommand\("(?<part>[a-z0-9 -]+)"(?:\s*,\s*"(?<part>[a-z0-9 -]+)")*\)\]\s*$')
    if ($attributes.Count -ne 1) { return }
    $parts = @($attributes[0].Groups['part'].Captures | ForEach-Object { $_.Value })
    $command = "$($coverage.toolName) $($parts -join ' ')"
    if (-not $commands.Contains($command)) { $_ }
})

foreach ($file in $candidates) {
    if ($PSCmdlet.ShouldProcess($file.FullName, 'Remove generated options absent from validated command coverage')) {
        Remove-Item -LiteralPath $file.FullName
        $relativePath = [IO.Path]::GetRelativePath($root, $file.FullName).Replace('\', '/')
        if ($ChangeManifest) { Add-Content -LiteralPath $ChangeManifest -Value $relativePath -Encoding utf8 }
        Write-Output $relativePath
    }
}
