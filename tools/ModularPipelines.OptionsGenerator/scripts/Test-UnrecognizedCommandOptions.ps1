$ErrorActionPreference = 'Stop'
$script = Join-Path $PSScriptRoot 'Remove-UnrecognizedCommandOptions.ps1'
$temporaryRoot = [IO.Path]::GetFullPath([IO.Path]::GetTempPath())
$fixture = Join-Path $temporaryRoot "command-options-pruning-$([guid]::NewGuid().ToString('N'))"
try {
    $package = Join-Path $fixture 'src/ModularPipelines.Fake'
    $options = New-Item -ItemType Directory -Path "$package/Options" -Force
    New-Item -ItemType Directory -Path "$package/Generated" -Force | Out-Null
    $coverage = "$package/Generated/Fake.CommandCoverage.json"
    $manifest = Join-Path $fixture 'changes.txt'
    $validCoverage = '{"formatVersion":1,"toolName":"fake","commandCount":2,"commands":["fake run","fake bundle create"]}'
    Set-Content -LiteralPath $coverage -Value $validCoverage
    foreach ($name in @('run', 'guide')) {
        Set-Content -LiteralPath "$options/$name.cs" -Value "// <auto-generated>`n[CliSubCommand(`"$name`")]`npublic record FakeOptions;"
    }
    Set-Content -LiteralPath "$options/nested-removed.cs" -Value "// <auto-generated>`n[CliSubCommand(`"bundle`", `"gone`")]`npublic record RemovedOptions;"
    Set-Content -LiteralPath "$options/nested-kept.cs" -Value "// <auto-generated>`n[CliSubCommand(`"bundle`", `"create`")]`npublic record KeptOptions;"
    Set-Content -LiteralPath "$options/handwritten.cs" -Value '[CliSubCommand("manual")] public record ManualOptions;'
    Set-Content -LiteralPath "$options/base.cs" -Value '// <auto-generated> public record BaseOptions;'
    & $script -RepositoryRoot $fixture -PackageDirectory 'src/ModularPipelines.Fake' -NamespacePrefix Fake -Tool fake -WhatIf | Out-Null
    if (-not (Test-Path -LiteralPath "$options/guide.cs")) { throw 'WhatIf removed a file.' }
    $removed = @(& $script -RepositoryRoot $fixture -PackageDirectory 'src/ModularPipelines.Fake' -NamespacePrefix Fake -Tool fake -ChangeManifest $manifest)
    if ((($removed | Sort-Object) -join ',') -ne 'src/ModularPipelines.Fake/Options/guide.cs,src/ModularPipelines.Fake/Options/nested-removed.cs' -or
        ((Get-Content -LiteralPath $manifest) -join ',') -ne ($removed -join ',')) { throw 'Expected only obsolete single and nested generated options in the deletion manifest.' }
    $again = @(& $script -RepositoryRoot "$fixture/" -PackageDirectory 'src/ModularPipelines.Fake' -NamespacePrefix Fake -Tool fake)
    if ($again.Count -ne 0) { throw 'Repeated pruning must be idempotent, including roots with a trailing separator.' }
    foreach ($name in @('run', 'nested-kept', 'handwritten', 'base')) {
        if (-not (Test-Path -LiteralPath "$options/$name.cs")) { throw "Preserved option missing: $name." }
    }
    $outsideRejected = $false
    try { & $script -RepositoryRoot $fixture -PackageDirectory '../outside' -NamespacePrefix Fake -Tool fake | Out-Null }
    catch { $outsideRejected = $_.Exception.Message.Contains('inside the repository') }
    if (-not $outsideRejected) { throw 'A package outside the repository must be rejected before pruning.' }
    foreach ($invalid in @(
        '{"formatVersion":1,"toolName":"other","commandCount":1,"commands":["other run"]}',
        '{"formatVersion":1,"toolName":"fake","commandCount":0,"commands":[]}',
        '{"formatVersion":1,"toolName":"fake","commandCount":2,"commands":["fake run"]}',
        '{"formatVersion":1,"toolName":"fake","commandCount":1,"commands":["other run"]}',
        '{"formatVersion":1,"toolName":"fake","commandCount":2,"commands":["fake run","fake run"]}'
    )) {
        Set-Content -LiteralPath $coverage -Value $invalid
        $failed = $false
        try { & $script -RepositoryRoot $fixture -PackageDirectory 'src/ModularPipelines.Fake' -NamespacePrefix Fake -Tool fake | Out-Null }
        catch { $failed = $true }
        if (-not $failed -or -not (Test-Path -LiteralPath "$options/run.cs")) { throw 'Invalid coverage must fail before removing options.' }
    }
}
finally {
    $resolved = [IO.Path]::GetFullPath($fixture)
    if (-not $resolved.StartsWith($temporaryRoot, [StringComparison]::OrdinalIgnoreCase) -or
        (Split-Path $resolved -Leaf) -notlike 'command-options-pruning-*') { throw 'Unsafe fixture cleanup path.' }
    Remove-Item -LiteralPath $resolved -Recurse -Force
}
$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path
$workflow = Get-Content -LiteralPath (Join-Path $repositoryRoot '.github/workflows/generate-cli-options.yml') -Raw
$pruneStep = $workflow.IndexOf('      - name: Prune obsolete generated Git options', [StringComparison]::Ordinal)
$provenanceStep = $workflow.IndexOf('      - name: Record generator provenance', [StringComparison]::Ordinal)
if ($pruneStep -lt 0 -or $pruneStep -gt $provenanceStep -or
    -not $workflow.Contains('run: tools/ModularPipelines.OptionsGenerator/scripts/Test-UnrecognizedCommandOptions.ps1', [StringComparison]::Ordinal) -or
    -not $workflow.Substring($pruneStep, $provenanceStep - $pruneStep).Contains('-Tool "${{ matrix.tool }}"', [StringComparison]::Ordinal)) {
    throw 'Git generation must test pruning and record its deletions before provenance.'
}
Write-Host 'Generated command option pruning tests passed.'
