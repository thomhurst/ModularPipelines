[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$HeadRef,
    [string]$HeadRepository = '',
    [string]$PullRequestAuthor = '',
    [string]$Repository = '',
    [Parameter(Mandatory)][AllowEmptyCollection()][string[]]$ChangedPath,
    [string]$RepositoryRoot = (Split-Path $PSScriptRoot -Parent),
    [string]$GitHubOutput
)

$ErrorActionPreference = 'Stop'

function New-GeneratedIntegrationValidationResult {
    param(
        [Parameter(Mandatory)][bool]$IsGeneratedIntegration,
        [Parameter(Mandatory)][string]$Reason,
        [string]$Tool = '',
        [string]$NamespacePrefix = '',
        [string]$Package = '',
        [string]$Solution = '',
        [string]$TestProject = ''
    )

    [pscustomobject]@{
        IsGeneratedIntegration = $IsGeneratedIntegration
        Tool = $Tool
        NamespacePrefix = $NamespacePrefix
        Package = $Package
        Solution = $Solution
        TestProject = $TestProject
        Reason = $Reason
    }
}

function Test-GeneratedIntegrationPath {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$PackagePrefix,
        [Parameter(Mandatory)][string]$NamespacePrefix,
        [Parameter(Mandatory)][string]$DocumentationPath,
        [Parameter(Mandatory)][string]$RepositoryRoot
    )

    if ($Path.Equals($DocumentationPath, [StringComparison]::OrdinalIgnoreCase)) {
        return $true
    }

    if (-not $Path.StartsWith($PackagePrefix, [StringComparison]::OrdinalIgnoreCase)) {
        return $false
    }

    $packagePath = $Path.Substring($PackagePrefix.Length)
    # Generation stages both assembly-wide API baselines, including for shared tool packages.
    if ($packagePath.Equals('PublicAPI.Shipped.txt', [StringComparison]::OrdinalIgnoreCase) -or
        $packagePath.Equals('PublicAPI.Unshipped.txt', [StringComparison]::OrdinalIgnoreCase) -or
        $packagePath.Equals(
            "Generated/$NamespacePrefix.CommandCoverage.json",
            [StringComparison]::OrdinalIgnoreCase) -or
        $packagePath.Equals(
            "Generated/$NamespacePrefix.Generation.json",
            [StringComparison]::OrdinalIgnoreCase)) {
        return $true
    }

    if (-not $packagePath.EndsWith('.Generated.cs', [StringComparison]::OrdinalIgnoreCase)) {
        return $false
    }

    $fullPath = Join-Path $RepositoryRoot $Path
    if (-not (Test-Path -LiteralPath $fullPath -PathType Leaf)) {
        return $true
    }

    $headerLines = @([System.IO.File]::ReadLines($fullPath) | Select-Object -First 5)
    $header = [string]::Join("`n", $headerLines)
    return $header.Contains('// <auto-generated>', [StringComparison]::Ordinal) -and
        $header.Contains('ModularPipelines.OptionsGenerator', [StringComparison]::Ordinal)
}

function Resolve-ToolPackageManifest {
    param(
        [Parameter(Mandatory)][string]$Tool,
        [Parameter(Mandatory)][string]$Package,
        [Parameter(Mandatory)][string]$RepositoryRoot
    )

    $manifestDirectory = Join-Path $RepositoryRoot "src/$Package/Generated"
    if (-not (Test-Path -LiteralPath $manifestDirectory -PathType Container)) {
        return $false
    }

    foreach ($manifest in Get-ChildItem -LiteralPath $manifestDirectory -Filter '*.CommandCoverage.json' -File) {
        $metadata = Get-Content -LiteralPath $manifest.FullName -Raw | ConvertFrom-Json
        if ($metadata.toolName -and
            $metadata.toolName.Equals($Tool, [StringComparison]::OrdinalIgnoreCase)) {
            return $manifest
        }
    }

    return $null
}

function Resolve-GeneratedIntegrationValidation {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$HeadRef,
        [Parameter(Mandatory)][AllowEmptyString()][string]$HeadRepository,
        [Parameter(Mandatory)][AllowEmptyString()][string]$PullRequestAuthor,
        [Parameter(Mandatory)][string]$Repository,
        [Parameter(Mandatory)][AllowEmptyCollection()][string[]]$ChangedPath,
        [Parameter(Mandatory)][string]$RepositoryRoot
    )

    $repositoryOwner = $Repository.Split('/', 2)[0]
    if ([string]::IsNullOrWhiteSpace($HeadRepository) -or
        -not $HeadRepository.Equals($Repository, [StringComparison]::OrdinalIgnoreCase) -or
        -not $PullRequestAuthor.Equals($repositoryOwner, [StringComparison]::OrdinalIgnoreCase)) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason 'The pull request is not owned by the generated-options automation identity.'
    }

    $branchPrefix = 'automated/update-cli-options-'
    if (-not $HeadRef.StartsWith($branchPrefix, [StringComparison]::Ordinal)) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason 'The pull request does not use an automated generated-options branch.'
    }

    $tool = $HeadRef.Substring($branchPrefix.Length)
    if ([string]::IsNullOrWhiteSpace($tool)) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason 'The generated-options branch does not identify a tool.'
    }

    $paths = @($ChangedPath |
        ForEach-Object { $_.Trim().Replace('\', '/') } |
        Where-Object { $_ } |
        Sort-Object -Unique)
    if ($paths.Count -eq 0) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason 'No changed paths were supplied.'
    }

    $packages = @($paths |
        ForEach-Object {
            if ($_ -match '^src/(?<package>ModularPipelines\.[^/]+)/') {
                $Matches.package
            }
        } |
        Sort-Object -Unique)
    if ($packages.Count -ne 1) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason "Expected one changed integration package; found $($packages.Count)."
    }

    $package = $packages[0]
    $coverageManifest = Resolve-ToolPackageManifest `
        -Tool $tool `
        -Package $package `
        -RepositoryRoot $RepositoryRoot
    if (-not $coverageManifest) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason "Tool '$tool' does not generate package '$package'."
    }
    $coverageSuffix = '.CommandCoverage.json'
    $namespacePrefix = $coverageManifest.Name.Substring(
        0,
        $coverageManifest.Name.Length - $coverageSuffix.Length)

    $packagePrefix = "src/$package/"
    $documentationPath = "docs/docs/mp-packages/cli/$tool.md"
    $unexpectedPaths = @($paths | Where-Object {
        -not (Test-GeneratedIntegrationPath `
                -Path $_ `
                -PackagePrefix $packagePrefix `
                -NamespacePrefix $namespacePrefix `
                -DocumentationPath $documentationPath `
                -RepositoryRoot $RepositoryRoot)
    })
    if ($unexpectedPaths.Count -gt 0) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason "Changes escape the generated integration: $($unexpectedPaths -join ', ')."
    }

    $solution = "src/$package/$package.slnx"
    if (-not (Test-Path -LiteralPath (Join-Path $RepositoryRoot $solution) -PathType Leaf)) {
        return New-GeneratedIntegrationValidationResult `
            -IsGeneratedIntegration $false `
            -Reason "Integration solution does not exist: $solution."
    }

    $testProject = "test/$package.UnitTests/$package.UnitTests.csproj"
    if (-not (Test-Path -LiteralPath (Join-Path $RepositoryRoot $testProject) -PathType Leaf)) {
        $testProject = ''
    }

    return New-GeneratedIntegrationValidationResult `
        -IsGeneratedIntegration $true `
        -Tool $tool `
        -NamespacePrefix $namespacePrefix `
        -Package $package `
        -Solution $solution `
        -TestProject $testProject `
        -Reason "All changes belong to generated tool '$tool' and package '$package'."
}

if ($MyInvocation.InvocationName -ne '.') {
    $result = Resolve-GeneratedIntegrationValidation `
        -HeadRef $HeadRef `
        -HeadRepository $HeadRepository `
        -PullRequestAuthor $PullRequestAuthor `
        -Repository $Repository `
        -ChangedPath $ChangedPath `
        -RepositoryRoot $RepositoryRoot
    Write-Host $result.Reason

    if ($GitHubOutput) {
        "is_generated_integration=$($result.IsGeneratedIntegration.ToString().ToLowerInvariant())" |
            Out-File -FilePath $GitHubOutput -Append
        "tool=$($result.Tool)" | Out-File -FilePath $GitHubOutput -Append
        "namespace_prefix=$($result.NamespacePrefix)" | Out-File -FilePath $GitHubOutput -Append
        "package=$($result.Package)" | Out-File -FilePath $GitHubOutput -Append
        "solution=$($result.Solution)" | Out-File -FilePath $GitHubOutput -Append
        "test_project=$($result.TestProject)" | Out-File -FilePath $GitHubOutput -Append
    }

    $result
}
